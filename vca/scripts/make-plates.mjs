// The domain bookplates at the sizes the pages draw them. The art is the main app's, 418 or 512 px
// square, and the places that show it are far smaller: a print on the home wall is 62 px tall on a
// phone, a card's is 90 to 165, the exam page's 34. Each is drawn from the smallest copy that is still
// sharp on the screen asking (srcset and sizes, components/bits.jsx and lib/art.js), not from the
// whole file.
//
// Writes, all committed (the build runs where only this app's own packages are installed, so it cannot
// make them; tests/unit/plates.test.mjs checks they are there and not stale):
//   public/art/224/<name>.webp   for a print at 1x on a desk and up to 3x on a phone's wall
//   public/art/448/<name>.webp   for a card on a phone at 3x or a desk at 2x (only where the art is larger)
//   src/data/plates.js           each plate's own size, a digest of its source, and the copies made
//
// Run it after the art or the domain list changes: npm run plates. Needs sharp, which the repo's root has.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { webpSize } from './webp-size.mjs';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(APP, '..');
const OUT = path.join(APP, 'public', 'art');
const require = createRequire(path.join(REPO, 'package.json'));
const sharp = require('sharp');

const { SUBJECT_COVERS } = await import(pathToFileURL(path.join(REPO, 'src/data/subject-covers.js')).href);
const { DOMAINS } = await import(pathToFileURL(path.join(APP, 'src/data/domains.js')).href);

// Lossy colour at a quality the line work keeps its hatching in, and a lighter alpha channel: the soft
// edge of a pen line needs fewer levels than the ink does (at these a copy's PSNR against the lossless
// downscale is 35 to 45 dB, and the alpha channel was a third of each file at 100).
const COPIES = [
  { width: 224, quality: 85, alphaQuality: 80 },
  { width: 448, quality: 80, alphaQuality: 75 },
];

const digest = (buf) => crypto.createHash('sha256').update(buf).digest('hex').slice(0, 16);
const writeIfChanged = (file, data) => {
  if (fs.existsSync(file) && Buffer.compare(fs.readFileSync(file), data) === 0) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
  return true;
};

const manifest = {};
let written = 0;
let before = 0;
let after = 0;
for (const id of [...new Set(DOMAINS.map((d) => d.art))]) {
  const cover = SUBJECT_COVERS[id];
  if (!cover) throw new Error(`plates: bookplate ${id} is not in subject-covers.js`);
  const name = path.basename(cover.src, '.webp');
  const source = fs.readFileSync(path.join(REPO, 'public', cover.src.replace(/^\//, '')));
  const size = webpSize(source);
  if (!size || size.width !== size.height) throw new Error(`plates: ${cover.src} is not a square WebP`);
  const sizes = [];
  before += source.length;
  for (const copy of COPIES) {
    // Never made larger than the art: a copy that is the print again, upscaled, would only weigh more.
    if (copy.width >= size.width) continue;
    const file = path.join(OUT, String(copy.width), `${name}.webp`);
    const bytes = await sharp(source)
      .resize(copy.width, copy.width, { fit: 'inside', kernel: 'lanczos3' })
      .webp({ quality: copy.quality, alphaQuality: copy.alphaQuality, effort: 6, smartSubsample: true })
      .toBuffer();
    if (writeIfChanged(file, bytes)) written += 1;
    sizes.push(copy.width);
    if (copy.width === 224) after += bytes.length;
  }
  manifest[name] = { width: size.width, source: digest(source), sizes };
}

const sorted = Object.entries(manifest).sort(([a], [b]) => (a < b ? -1 : 1));
const moduleText = [
  '// AUTO-GENERATED by vca/scripts/make-plates.mjs (npm run plates). Do not edit; run it after the art or the domain list changes.',
  '// For each domain plate in the main app\'s art: its own width, a digest of that file, and the widths of the smaller copies in',
  '// public/art/<width>/. lib/art.js turns this into the srcset an <img> offers the browser.',
  'export const PLATES = {',
  ...sorted.map(([name, e]) => `  '${name}': { width: ${e.width}, source: '${e.source}', sizes: [${e.sizes.join(', ')}] },`),
  '};',
  '',
].join('\n');
if (writeIfChanged(path.join(APP, 'src', 'data', 'plates.js'), Buffer.from(moduleText))) written += 1;
console.log(`plates: ${sorted.length} prints, ${written} files written; the art is ${Math.round(before / 1024)} KB, its 224 px copies ${Math.round(after / 1024)} KB`);
