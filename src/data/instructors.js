// ============================================================
// Helper: lookup instructor by slug or by name match against
// the lecturer field in curriculum.js topics
// ============================================================
export function getInstructorBySlug(slug) {
  return INSTRUCTORS[slug] || null;
}

export function getInstructorByLecturerString(lecturerString) {
  if (!lecturerString) return null;
  // Normalize: drop "(KB)" tags + extra whitespace + extra notes
  const cleaned = String(lecturerString)
    .replace(/\s*\([^)]+\)\s*/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
  // Try exact match against instructor names (Thai or English)
  for (const ins of Object.values(INSTRUCTORS)) {
    const en = (ins.nameEn || '').toLowerCase();
    const th = (ins.nameTh || '').toLowerCase();
    if (cleaned === en || cleaned === th) return ins;
    if (cleaned.includes(en) || (th && cleaned.includes(th))) return ins;
    if (en.startsWith(cleaned) || (th && th.startsWith(cleaned))) return ins;
  }
  return null;
}

