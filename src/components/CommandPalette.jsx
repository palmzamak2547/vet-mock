// Truncate a label for the result row. The result button is a single
// line with ellipsis CSS, but we still cap at the source so the
// pre-lowered haystack stays small and tooltips don't blow up either.
const MAX_LABEL_LEN = 60;
function trunc(s) {
  const str = (s || '').toString().replace(/\s+/g, ' ').trim();
  return str.length > MAX_LABEL_LEN ? str.slice(0, MAX_LABEL_LEN - 1) + '…' : str;
}

// Safely read & JSON-parse a localStorage key. Returns fallback on
// any failure (corrupted JSON, disabled storage, SSR, …). Palette
// should never crash because the user's localStorage is dirty.
function safeReadLS(key, fallback) {
  if (typeof window === 'undefined' || !window.localStorage) return fallback;
  try {
    const raw = window.localStorage.getItem(key);
    if (!raw) return fallback;
    const parsed = JSON.parse(raw);
    return parsed == null ? fallback : parsed;
  } catch {
    return fallback;
  }
}

// Each cached entry has shape:
//   { type, label, hint, icon, kw, payload, _labelLc, _hayLc }
//
//   type      'action' | 'subject' | 'summary' | 'instructor' | 'question'
//   payload   data needed by the dispatcher (action key, subject id,
//             Q ref, instructor object, …) — keeps the cached entry
//             pure data so it can outlive any component instance.
//   _labelLc  label.toLowerCase() — used by fuzzyFilter so we don't
//             re-lowercase 1700 strings per keystroke
//   _hayLc    (label + ' ' + kw).toLowerCase() — same idea
function buildStaticItems() {
  // The cache is keyed on the bank size: QB is lazy-loaded and mutated in
  // place, so a cache built before the load (or before a year switch pulls a
  // different bank) held stale question rows for the rest of the session —
  // search results and their counts disagreed with the app.
  if (_staticItemsCache && _staticItemsCache.qbLen === QB.length) return _staticItemsCache.items;
  const items = [];

  const push = (it) => {
    const labelLc = (it.label || '').toLowerCase();
    items.push({
      ...it,
      _labelLc: labelLc,
      _hayLc: labelLc + ' ' + (it.kw || '').toLowerCase(),
    });
  };

  // Quick actions — DERIVED from the feature registry (single source of
  // truth shared with HomeView), plus two nav-only entries that aren't
  // standalone "features": home (navigation) and bookmarks (a practice
  // mode, not a screen). payload carries the invoke descriptor that
  // runItem() interprets. Deriving here means adding a feature to the
  // registry makes it searchable automatically — closing the old gap
  // where race/groups/lab/leaderboard/contribute/review-queue/mini-game
  // were navigable from somewhere but never showed up in ⌘K.
  push({ type: 'action', payload: { kind: 'view', view: 'home' }, label: 'หน้าแรก', hint: 'Home', icon: '🏠', kw: 'home หน้าแรก main' });
  push({ type: 'action', payload: { kind: 'bookmarks' }, label: 'Bookmarks', hint: 'ข้อที่บันทึกไว้', icon: '⭐', kw: 'bookmark saved star ดาว ข้อบันทึก' });
  for (const f of FEATURES) {
    push({ type: 'action', payload: f.invoke, label: f.label, hint: f.hint, icon: f.icon, kw: f.kw, category: f.category, featureId: f.id });
  }

  // VetWiki articles — governed knowledge is searchable from anywhere.
  // Keywords include the summary so Thai queries reach English-titled topics.
  if (FEATURE_FLAGS.VETWIKI_ENABLED !== false) {
    for (const t of listTopics()) {
      push({
        type: 'wiki',
        payload: { subject: t.subject, topic: t.topic },
        label: t.title,
        hint: 'VetWiki, บอกที่มาได้ทุกส่วน',
        icon: '🧬',
        kw: `vetwiki wiki ${t.title} ${t.summary || ''} ${t.subject} ${t.topic}`,
      });
    }
  }

  // Subjects
  for (const s of SUBJECTS) {
    if (s.id === 'all') continue;
    push({
      type: 'subject',
      payload: s.id,
      year: yearForSubject(s.id),
      label: s.name,
      hint: s.name_en || s.code || '',
      icon: s.icon || '📚',
      kw: `${s.id} ${s.name} ${s.name_en || ''} ${s.code || ''}`,
    });
  }

  // Upcoming exams — so "สอบ zoonoses", a course code, or "กลางภาค" lands on
  // the real date/time/room instead of the student asking in the group chat.
  for (const yr of [1, 2, 3, 4, 5]) {
    for (const e of getUpcomingExams(`y${yr}`)) {
      if (e.daysLeft < 0) continue; // past exams are noise in a search box
      push({
        type: 'exam',
        payload: 'schedule',
        year: yr,
        label: `สอบ ${e.title}`,
        hint: `${fmtThaiDate(e.date)}, ${e.time}, ${e.location}`,
        icon: e.icon || '📅',
        kw: `exam สอบ ${e.term === 'midterm' ? 'กลางภาค midterm' : 'ปลายภาค final'} ${e.code} ${e.title} ${e.subject} ${e.location}`,
      });
    }
  }

  // Video summaries
  for (const s of Object.values(VIDEO_SUMMARIES || {})) {
    if (!s?.title) continue;
    push({
      type: 'summary',
      payload: null,
      label: s.title,
      hint: `สรุปคลิป, ${(s.subject || '').toUpperCase()}`,
      icon: '📝',
      kw: `${s.title} ${s.subject || ''} ${s.instructor || ''} summary สรุป คลิป`,
    });
  }

  // Instructors
  for (const ins of (ALL_INSTRUCTORS || [])) {
    push({
      type: 'instructor',
      payload: ins,
      label: `อ. ${ins.nameTh || ins.nameEn}`,
      hint: `👨‍🏫 ${ins.nameEn}, ${(ins.subjects || []).join('/').toUpperCase()}`,
      icon: '👨‍🏫',
      kw: `${ins.nameEn} ${ins.nameTh || ''} ${(ins.aliases || []).join(' ')} ${ins.position || ''} ${(ins.areas || []).join(' ')} instructor faculty อาจารย์`,
    });
  }

  // Question stems
  const seenQText = new Set();
  for (const q of (QB || [])) {
    if (!isQuestionDeliverable(q)) continue;
    if (!q?.q || typeof q.q !== 'string') continue;
    const stem = q.q.slice(0, 100);
    const dedupeKey = q.subject + ':' + stem.slice(0, 50);
    if (seenQText.has(dedupeKey)) continue;
    seenQText.add(dedupeKey);
    push({
      type: 'question',
      payload: { subject: q.subject, id: q.id },
      label: stem.length < q.q.length ? stem + '…' : stem,
      hint: `${q.subject?.toUpperCase() || 'Q'}, Q${q.id}${q.tags?.length ? ', ' + q.tags.slice(0, 2).join(', ') : ''}`,
      icon: '❓',
      kw: stem + ' ' + (q.tags || []).join(' '),
    });
  }

  // User-authored flashcards (Highlight → Flashcard). Reads localStorage
  // via the dedicated module so a corrupted blob or quota-exceeded
  // state can't bring the palette down. front+back together become
  // the searchable haystack so even back-of-card terms hit.
  let flashcards = [];
  try {
    flashcards = loadUserFlashcards() || [];
  } catch {
    flashcards = [];
  }
  for (const card of flashcards) {
    if (!card || typeof card.front !== 'string' || !card.front.trim()) continue;
    const back = (card.back || '').toString();
    push({
      type: 'flashcard',
      payload: card,
      label: trunc(card.front),
      hint: 'Flashcard',
      icon: '⚡',
      kw: (card.front + ' ' + back).toLowerCase(),
    });
  }

  // Per-Q notes — stored as { [qIdOrCompoundKey]: noteText } under
  // 'vmx-notes'. We surface each non-empty note as its own row so the
  // user can fuzzy-search their own annotations and jump back to the
  // Q. Key shape is opaque to us; we pass it through as the payload.
  const notesMap = safeReadLS(NOTES_LS_KEY, null);
  if (notesMap && typeof notesMap === 'object' && !Array.isArray(notesMap)) {
    for (const [key, raw] of Object.entries(notesMap)) {
      const text = typeof raw === 'string' ? raw : (raw && typeof raw === 'object' ? (raw.text || raw.note || '') : '');
      const trimmed = (text || '').toString().trim();
      if (!trimmed) continue;
      push({
        type: 'q-note',
        payload: key,
        label: trunc(trimmed),
        hint: 'โน้ต Q ' + key,
        icon: '📝',
        kw: trimmed.toLowerCase(),
      });
    }
  }

  _staticItemsCache = { qbLen: QB.length, items };
  return items;
}

// Dispatch table — translates a cached item back into an action.
// Keeps the item array pure data so we don't have to rebuild closures.
function runItem(item, handlers) {
  const { goView, setSubject, setPracticeMode, openInstructor, openVoiceSettings, onPractice, onPanic, onSketch, onOpenWiki } = handlers;
  switch (item.type) {
    case 'wiki': onOpenWiki?.(item.payload.subject, item.payload.topic); return;
    case 'exam': goView?.(item.payload); return; // payload = 'schedule'
    case 'action': {
      // payload is now an invoke descriptor (from the registry) or one of
      // the two nav-only specials (home view / bookmarks practice mode).
      const inv = item.payload;
      if (!inv || typeof inv !== 'object') return;
      switch (inv.kind) {
        case 'view':      goView?.(inv.view); return;
        case 'practice':  onPractice?.(inv); return;
        case 'panic':     onPanic?.(inv.timeKey || '30'); return;
        case 'event':     try { window.dispatchEvent(new Event(inv.event)); } catch { /* no-op */ } return;
        case 'sketch':    onSketch?.(); return;
        case 'external':  if (inv.url) window.location.assign(inv.url); return;
        // voice-settings opens an overlay instead of navigating — keeps
        // the user on the current Q if they triggered from ExamView.
        case 'voice':     openVoiceSettings?.(); return;
        case 'bookmarks': setPracticeMode?.('bookmarks'); goView?.('config'); return;
        default: return;
      }
    }
    case 'subject':    setSubject?.(item.payload); goView?.('topic-select'); return;
    case 'summary':    goView?.('videos'); return;
    case 'instructor': openInstructor?.(item.payload); return;
    case 'question':   setSubject?.(item.payload.subject); setPracticeMode?.('all'); goView?.('config'); return;
    // User flashcard → jump into SR review. v1 doesn't scroll to the
    // specific card; the user can rip through the deck from the top.
    case 'flashcard':  goView?.('sr-session'); return;
    // Per-Q note → open Bookmarks practice so the user can fuzzy-find
    // their noted Q in a quick-review set. Cheapest navigation that
    // gets them into a context where the note matters.
    case 'q-note':     setPracticeMode?.('bookmarks'); goView?.('config'); return;
    default: return;
  }
}

// Ranked (item, score) pairs — the grouped renderer needs scores to order
// GROUPS by their best hit while keeping items ranked inside each group.
function rankItems(items, query) {
  const q = query.trim().toLowerCase();
  const tokens = q.split(/\s+/).filter(Boolean);
  const scored = [];
  for (let i = 0; i < items.length; i++) {
    const item = items[i];
    let score = 0;
    let allMatch = true;
    for (const t of tokens) {
      const pos = item._hayLc.indexOf(t);
      if (pos < 0) { allMatch = false; break; }
      const labelPos = item._labelLc.indexOf(t);
      score += labelPos >= 0 ? (100 - labelPos) : (50 - Math.min(50, pos));
      if (item._labelLc.startsWith(t)) score += 200;
    }
    if (allMatch) scored.push({ item, score });
  }
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, MAX_RESULTS);
}

