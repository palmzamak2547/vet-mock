// ── The palette ──────────────────────────────────────────────────────────

export default function CommandPalette({
  open,
  onClose,
  signedIn = false,
  scaffold = false,
  hasSupabase = true,
  selectedYear,
  ...handlers
}) {
  const [query, setQuery] = useState('');
  const [debouncedQuery, setDebouncedQuery] = useState('');
  const [activeIdx, setActiveIdx] = useState(0);
  const [expandedGroups, setExpandedGroups] = useState(() => new Set());
  const [placeholderIdx, setPlaceholderIdx] = useState(0);
  // sourceState: { [id]: { status: 'loading'|'ready'|'error', entries } }
  const [sourceState, setSourceState] = useState({});
  const [ask, setAsk] = useState(null); // null | loading | done | error
  const [agent, setAgent] = useState(null); // null | loading | confirm | refused | error
  // Touch has no Ctrl — the chip and hints must speak tap, not keys.
  const coarsePointer = useMemo(() => typeof matchMedia === 'function' && matchMedia('(pointer: coarse)').matches, []);
  const inputRef = useRef(null);

  // Voice input — the browser's own recognizer (th-TH), no key, no dependency.
  // The transcript lands in the SAME query state, so everything downstream
  // (streamed results, the ask row, auto-ask, the ⚡ agent row) works on a
  // spoken sentence exactly as on a typed one. Hidden where unsupported.
  const [voice, setVoice] = useState(null); // null | 'listening' | 'denied' | 'error'
  const recRef = useRef(null);
  const speechSupported = useMemo(
    () => typeof window !== 'undefined' && !!(window.SpeechRecognition || window.webkitSpeechRecognition),
    [],
  );
  const toggleVoice = () => {
    if (recRef.current) { try { recRef.current.stop(); } catch { /* already stopping */ } return; }
    const SR = window.SpeechRecognition || window.webkitSpeechRecognition;
    if (!SR) return;
    const rec = new SR();
    rec.lang = 'th-TH';
    rec.interimResults = true; // live transcript → results stream while speaking
    rec.continuous = false;
    let finalT = '';
    rec.onresult = (e) => {
      const t = Array.from(e.results).map((r) => r[0]?.transcript || '').join('').trim();
      if (t) { finalT = t; setQuery(t); }
    };
    rec.onerror = (e) => { setVoice(e?.error === 'not-allowed' || e?.error === 'service-not-allowed' ? 'denied' : 'error'); };
    rec.onend = () => {
      recRef.current = null;
      setVoice((v) => (v === 'listening' ? null : v));
      inputRef.current?.focus();
      // Hands-free: a finished spoken sentence acts on itself. A command
      // fetches its plan (execution still waits for the ทำเลย tap), a
      // question asks; a plain phrase just leaves its search results.
      // Action is checked first — "จัดข้อสอบ 20 ข้อได้ไหม" is a polite
      // command, not a question about the world.
      const t = finalT.trim();
      if (t.length >= 6 && looksLikeAction(t)) { lastAutoAsk.current = t; runAgent(t); }
      else if (t.length >= 8 && looksLikeQuestion(t)) { lastAutoAsk.current = t; runAsk(t); }
    };
    recRef.current = rec;
    setVoice('listening');
    try { rec.start(); } catch { recRef.current = null; setVoice('error'); }
  };
  useEffect(() => () => { try { recRef.current?.stop(); } catch { /* unmount race */ } }, []);
  const dialogRef = useModalFocus({ active: open, onClose, initialFocusRef: inputRef });
  const listRef = useRef(null);

  const staticItems = useMemo(() => buildStaticItems(), []);
  const visibleFeatureIds = useMemo(() => new Set(
    visibleFeatures(FEATURES, { signedIn, scaffold, hasSupabase, selectedYear }).map((feature) => feature.id),
  ), [signedIn, scaffold, hasSupabase, selectedYear]);

  // Async sources stream in while the palette is open. Each one caches at
  // module level (omni-sources), so the spinner shows once per session.
  useEffect(() => {
    if (!open) return undefined;
    let alive = true;
    for (const src of OMNI_SOURCES) {
      setSourceState((s) => (s[src.id]?.status === 'ready' ? s : { ...s, [src.id]: { status: 'loading', entries: [] } }));
      src.load().then(
        (entries) => { if (alive) setSourceState((s) => ({ ...s, [src.id]: { status: 'ready', entries } })); },
        (err) => {
          // The chip says "ออฟไลน์"; the console says why. A silent error
          // state cost 20 minutes of guessing the first time this shipped.
          console.error('[omni-source]', src.id, err);
          if (alive) setSourceState((s) => ({ ...s, [src.id]: { status: 'error', entries: [] } }));
        },
      );
    }
    return () => { alive = false; };
  }, [open]);

  const items = useMemo(() => {
    const base = staticItems.filter((item) => {
      if (item.featureId && !visibleFeatureIds.has(item.featureId)) return false;
      if (item.type === 'subject' && selectedYear != null && item.year != null) {
        return Number(item.year) === Number(selectedYear);
      }
      return true;
    });
    const async_ = Object.values(sourceState).flatMap((s) => s.entries || []);
    return base.concat(async_);
  }, [staticItems, visibleFeatureIds, selectedYear, sourceState]);

  const handlersRef = useRef(handlers);
  handlersRef.current = handlers;

  useEffect(() => {
    if (query === debouncedQuery) return undefined;
    const t = setTimeout(() => setDebouncedQuery(query), 60);
    return () => clearTimeout(t);
  }, [query, debouncedQuery]);

  // Rotating placeholder — decorative, so it parks on the first example
  // when the user asked for reduced motion.
  useEffect(() => {
    if (!open) return undefined;
    if (typeof matchMedia === 'function' && matchMedia('(prefers-reduced-motion: reduce)').matches) return undefined;
    const t = setInterval(() => setPlaceholderIdx((i) => (i + 1) % PLACEHOLDERS.length), 3500);
    return () => clearInterval(t);
  }, [open]);

  const hasQuery = !!debouncedQuery.trim();
  const intents = useMemo(() => (hasQuery ? detectIntents(debouncedQuery) : []), [hasQuery, debouncedQuery]);

  // Grouped result model. With a query: rank everything flat, then bucket
  // by type, order groups by their best-ranked hit. Without: recents first,
  // then the curated group order.
  const view = useMemo(() => {
    const recents = hasQuery ? [] : readRecents().map((r) => ({
      ...r,
      _labelLc: (r.label || '').toLowerCase(),
      _hayLc: (r.label || '').toLowerCase(),
      _recent: true,
    }));

    let groups;
    if (!hasQuery) {
      const buckets = new Map();
      if (recents.length) buckets.set('recent', recents);
      for (const item of items) {
        const key = item.type;
        if (!buckets.has(key)) buckets.set(key, []);
        buckets.get(key).push(item);
      }
      groups = [...buckets.entries()]
        .sort((a, b) => GROUP_ORDER.indexOf(a[0]) - GROUP_ORDER.indexOf(b[0]))
        .map(([type, list]) => ({ type, list }));
    } else {
      const ranked = rankItems(items, debouncedQuery);
      const buckets = new Map();
      for (const { item } of ranked) {
        const key = item.type;
        if (!buckets.has(key)) buckets.set(key, []);
        buckets.get(key).push(item);
      }
      groups = [...buckets.entries()].map(([type, list]) => ({ type, list }));
    }

    // Apply per-group caps and lay out the flat keyboard order. A
    // question-shaped query puts the ask row first, so plain Enter asks.
    const flat = [];
    const askInFlow = hasQuery && looksLikeQuestion(debouncedQuery.trim());
    if (askInFlow) flat.push({ type: 'ask' });
    const sections = groups.map(({ type, list }) => {
      const cap = expandedGroups.has(type) ? GROUP_CAP_EXPANDED : GROUP_CAP;
      const shown = list.slice(0, cap);
      const startIdx = flat.length;
      flat.push(...shown);
      return { type, items: shown, startIdx, total: list.length, shown: shown.length };
    });
    return { sections, flat, askInFlow };
  }, [items, debouncedQuery, hasQuery, expandedGroups]);

  const sourcesLoading = Object.values(sourceState).some((s) => s.status === 'loading');

  const indexTotal = items.length;

  useEffect(() => {
    if (open) {
      setQuery('');
      setDebouncedQuery('');
      setActiveIdx(0);
      setExpandedGroups(new Set());
      setAsk(null);
      setAgent(null);
      setVoice(null);
    } else {
      try { recRef.current?.stop(); } catch { /* closing while idle */ }
    }
    return undefined;
  }, [open]);

  useEffect(() => { setActiveIdx(0); }, [debouncedQuery]);

  useEffect(() => {
    if (!listRef.current) return;
    const el = listRef.current.querySelector(`[data-flat-idx="${activeIdx}"]`);
    if (el && typeof el.scrollIntoView === 'function') {
      el.scrollIntoView({ block: 'nearest' });
    }
  }, [activeIdx]);

  if (!open) return null;

  const fire = (item) => {
    if (item.type === 'ask') { runAsk(); return; }
    pushRecent(item);
    if (item.type === 'library-doc') {
      // Same open logic as the shelf: PDFs navigate to the reader instantly
      // (the reader mints the link while its own chunk loads), everything
      // else opens as a plain URL in a new tab.
      const doc = item.payload;
      recordRecentDoc(doc);
      onClose();
      if (docOpenMode(doc).action === 'read') {
        handlersRef.current.onOpenLibraryDoc?.(readerPayload(doc));
        return;
      }
      // Open the tab synchronously — popup blockers only trust window.open
      // during the click, and the mint takes longer than that trust lasts.
      const win = window.open('', '_blank');
      if (win) { try { win.opener = null; } catch { /* hardened browsers */ } }
      resolveDocUrl(doc).then(
        (url) => {
          if (win) win.location.replace(url);
          else window.open(url, '_blank', 'noopener,noreferrer');
        },
        () => {
          if (win) { try { win.close(); } catch { /* already gone */ } }
          handlersRef.current.goView?.('library'); // resolution failed → land on the shelf, which shows its own error UI
        },
      );
      return;
    }
    if (item.type === 'drug') {
      try { window.dispatchEvent(new Event('vmx-open-vetcalc')); } catch { /* no-op */ }
      onClose();
      return;
    }
    runItem(item, handlersRef.current);
    onClose();
  };

  const runAsk = async (spoken) => {
    const question = (typeof spoken === 'string' ? spoken : query).trim();
    if (question.length < 8 || ask?.phase === 'loading') return;
    setAsk({ phase: 'loading' });
    try {
      const res = await fetch('/api/wiki-explain', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ question }),
      });
      if (res.status === 503) { setAsk({ phase: 'error', message: 'ยังไม่ได้เปิดใช้การถามจากคลังความรู้ — เนื้อหาทั้งหมดยังอ่านได้ตามปกติ' }); return; }
      if (res.status === 429) { setAsk({ phase: 'error', message: 'ถามบ่อยเกินไป ลองใหม่ในอีกสักครู่' }); return; }
      if (!(res.headers.get('content-type') || '').includes('application/json')) {
        setAsk({ phase: 'error', message: 'การถามใช้ได้เฉพาะบนเว็บจริง (vetmock.vercel.app)' }); return;
      }
      if (!res.ok) { setAsk({ phase: 'error', message: 'ตอบไม่สำเร็จ ลองใหม่อีกครั้ง' }); return; }
      const data = await res.json();
      // Isomorphic guard: rebuild the allowed-citation map from THIS
      // build's own generated citation index and validate again. The index
      // carries exactly what validateAnswer consumes (topicId + verified per
      // sectionId, drift-gated against the corpus), so the guard costs ~40 KB
      // instead of the full corpus barrel — and it is TIGHTER than loading
      // topics: only sections the server says it supplied, intersected with
      // sections this build really has, can validate a citation.
      const [{ validateAnswer, ANSWER_SUPPORT_LABEL }, { CITATION_INDEX }] = await Promise.all([
        import('../lib/vetwiki/answer.js'),
        import('../lib/vetwiki/citation-index.generated.js'),
      ]);
      const allowed = new Map();
      for (const m of data.meta?.sections || []) {
        const id = String(m?.sectionId || '');
        const hit = CITATION_INDEX[id];
        if (!hit) continue; // server named a section this build does not have
        allowed.set(id, { sectionId: id, topicId: hit[0], verified: !!hit[1] });
      }
      const { claims } = validateAnswer(data.claims, allowed);
      if (!claims.length) { setAsk({ phase: 'error', message: 'ยังตอบจากเนื้อหาที่มีไม่ได้' }); return; }
      setAsk({ phase: 'done', claims, sections: data.meta?.sections || [], labels: ANSWER_SUPPORT_LABEL });
    } catch {
      setAsk({ phase: 'error', message: 'เชื่อมต่อไม่ได้ ลองใหม่อีกครั้ง' });
    }
  };

  // A settled question with an empty list should not need ANY key — the
  // person already typed what they want to know. Once per query string;
  // never while sources are still streaming in (results may yet arrive).
  const lastAutoAsk = useRef('');
  useEffect(() => {
    const q = debouncedQuery.trim();
    if (q.length < 12 || !looksLikeQuestion(q)) return;
    if (sourcesLoading) return;
    if (view.flat.some((i) => i.type !== 'ask')) return;
    if (lastAutoAsk.current === q || ask?.phase === 'loading') return;
    lastAutoAsk.current = q;
    runAsk();
    // eslint-disable-next-line react-hooks/exhaustive-deps -- runAsk reads live state
  }, [debouncedQuery, view, sourcesLoading]);

  const runAgent = async (spoken) => {
    const utterance = (typeof spoken === 'string' ? spoken : query).trim();
    if (utterance.length < 6 || agent?.phase === 'loading') return;
    setAgent({ phase: 'loading' });
    try {
      const res = await fetch('/api/agent-action', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ utterance }),
      });
      if (res.status === 503) { setAgent({ phase: 'error', message: 'ยังไม่ได้เปิดใช้ผู้ช่วยสั่งงาน' }); return; }
      if (res.status === 429) { setAgent({ phase: 'error', message: 'สั่งบ่อยเกินไป ลองใหม่ในอีกสักครู่' }); return; }
      if (!(res.headers.get('content-type') || '').includes('application/json')) {
        setAgent({ phase: 'error', message: 'ผู้ช่วยสั่งงานใช้ได้เฉพาะบนเว็บจริง (vetmock.vercel.app)' }); return;
      }
      if (!res.ok) { setAgent({ phase: 'error', message: 'สั่งไม่สำเร็จ ลองใหม่อีกครั้ง' }); return; }
      const data = await res.json();
      if (!data.action) { setAgent({ phase: 'refused', message: data.reason || 'ยังไม่มีสิ่งที่ตรงกับคำสั่งนี้ในแอป' }); return; }
      // The server already validated every id against the live catalog —
      // the student still confirms before anything runs.
      setAgent({ phase: 'confirm', action: data.action, say: data.say });
    } catch {
      setAgent({ phase: 'error', message: 'เชื่อมต่อไม่ได้ ลองใหม่อีกครั้ง' });
    }
  };

  const executeAgent = (action) => {
    const h = handlersRef.current;
    if (action.type === 'practice') { h.onPractice?.(action.invoke); onClose(); return; }
    if (action.type === 'library') {
      try { sessionStorage.setItem('vmx-library-q', action.subjectName || ''); } catch { /* nicety */ }
      h.goView?.('library'); onClose(); return;
    }
    if (action.type === 'wiki') { h.onOpenWiki?.(action.subject, action.topic); onClose(); return; }
    if (action.type === 'feature') {
      const f = FEATURES.find((x) => x.id === action.id);
      if (f) runItem({ type: 'action', payload: f.invoke }, h);
      onClose();
    }
  };

  const openLibraryShelf = (meta) => {
    try { sessionStorage.setItem('vmx-library-subject', meta.id || ''); } catch { /* nicety */ }
    handlersRef.current.goView?.('library');
    onClose();
  };
  const practiceSubject = (subjectId) => {
    handlersRef.current.setSubject?.(subjectId);
    handlersRef.current.goView?.('topic-select');
    onClose();
  };

  const handleKey = (e) => {
    if (e.key === 'Escape') { e.preventDefault(); onClose(); }
    else if (e.key === 'ArrowDown') {
      e.preventDefault();
      setActiveIdx((i) => Math.min(view.flat.length - 1, i + 1));
    } else if (e.key === 'ArrowUp') {
      e.preventDefault();
      setActiveIdx((i) => Math.max(0, i - 1));
    } else if (e.key === 'Enter' && (e.ctrlKey || e.metaKey)) {
      e.preventDefault();
      runAsk();
    } else if (e.key === 'Enter') {
      e.preventDefault();
      const item = view.flat[activeIdx];
      if (item) fire(item);
    }
  };

  return (
    <div
      className="vmx-modal-overlay"
      onClick={onClose}
      style={{ alignItems: 'flex-start', paddingTop: 'min(12vh, 90px)', backdropFilter: 'blur(5px)' }}
    >
      <div
        ref={dialogRef}
        className="vmx-modal"
        onClick={(e) => e.stopPropagation()}
        style={{ maxWidth: 640, padding: 0, overflow: 'hidden' }}
        role="dialog"
        aria-modal="true"
        tabIndex={-1}
        data-vmx-modal="true"
        aria-label="ค้นหาอัจฉริยะ"
      >
        <div className="vmx-omni-topbar" aria-hidden="true" />

        {/* Search input */}
        <div style={{
          display: 'flex',
          alignItems: 'center',
          gap: 12,
          padding: '16px 20px',
          borderBottom: '1px solid var(--clr-border)',
        }}>
          <span className="vmx-omni-spark" aria-hidden="true" style={{ fontSize: 18, color: 'var(--clr-sage-text)' }}>✦</span>
          <input
            ref={inputRef}
            type="text"
            value={query}
            onChange={(e) => {
              setQuery(e.target.value);
              // Typing means the person moved on — clear a stale mic hint.
              setVoice((v) => (v === 'denied' || v === 'error' ? null : v));
            }}
            onKeyDown={handleKey}
            placeholder={PLACEHOLDERS[placeholderIdx]}
            aria-label="ค้นหาใน VetMock"
            style={{
              all: 'unset',
              flex: 1,
              fontSize: 16,
              color: 'var(--clr-ink)',
              fontFamily: 'inherit',
              minWidth: 0,
            }}
            autoComplete="off"
            spellCheck="false"
          />
          {speechSupported && (
            <button
              type="button"
              onClick={toggleVoice}
              aria-label={voice === 'listening' ? 'หยุดฟังเสียง' : 'สั่งงานหรือถามด้วยเสียง'}
              aria-pressed={voice === 'listening'}
              title={voice === 'listening' ? 'หยุดฟังเสียง' : 'สั่งงานหรือถามด้วยเสียง'}
              style={{
                all: 'unset', cursor: 'pointer', width: 34, height: 34, display: 'flex',
                alignItems: 'center', justifyContent: 'center', borderRadius: 8, flexShrink: 0,
                color: voice === 'listening' ? 'var(--clr-rose-text)' : 'var(--clr-ink-soft)',
                background: voice === 'listening' ? 'color-mix(in srgb, currentColor 12%, transparent)' : 'transparent',
              }}
            >
              <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                <path d="M12 2a3 3 0 0 0-3 3v6a3 3 0 0 0 6 0V5a3 3 0 0 0-3-3z" />
                <path d="M19 10v1a7 7 0 0 1-14 0v-1" />
                <line x1="12" y1="18" x2="12" y2="22" />
              </svg>
            </button>
          )}
          <span style={{
            fontFamily: 'var(--vmx-mono)',
            fontSize: 11,
            color: 'var(--clr-ink-soft)',
            padding: '2px 6px',
            border: '1px solid var(--clr-border)',
            borderRadius: 4,
          }}>esc</span>
        </div>

        {/* Voice status lives BELOW the row: inline it squeezed the input
            to 52px on a 375px phone whenever the denied hint showed. */}
        {voice && (
          <div aria-live="polite" style={{
            padding: '6px 20px 0',
            fontSize: 11.5,
            color: voice === 'listening' ? 'var(--clr-rose-text)' : 'var(--clr-ink-soft)',
          }}>
            {voice === 'listening'
              ? 'ฟังอยู่… พูดได้เลย'
              : voice === 'denied'
                ? 'ไมค์ถูกปิดสิทธิ์ในเบราว์เซอร์ — เปิดสิทธิ์ไมโครโฟนแล้วลองใหม่'
                : 'ฟังไม่สำเร็จ ลองใหม่อีกครั้ง'}
          </div>
        )}

        {/* Ask-the-corpus. Question-shaped queries put this row FIRST in
            the keyboard order (plain Enter asks); other queries keep it as
            a tap/click affordance so Enter still opens the top result. */}
        {hasQuery && debouncedQuery.trim().length >= 8 && (
          <button
            type="button"
            onClick={runAsk}
            data-flat-idx={view.askInFlow ? 0 : undefined}
            onMouseEnter={view.askInFlow ? () => setActiveIdx(0) : undefined}
            className="vmx-omni-row"
            style={{
              all: 'unset', cursor: 'pointer', display: 'flex', alignItems: 'center', gap: 10,
              boxSizing: 'border-box', width: 'calc(100% - 24px)', margin: '8px 12px 0',
              padding: '10px 12px', minHeight: 44, borderRadius: 10,
              border: '1px dashed color-mix(in srgb, var(--clr-sage) 55%, var(--clr-border))',
              background: view.askInFlow && activeIdx === 0 ? 'var(--clr-surface-2)' : 'transparent',
              color: 'var(--clr-ink)', fontSize: 13,
            }}
          >
            <span className="vmx-omni-spark" aria-hidden="true" style={{ color: 'var(--clr-sage-text)' }}>✦</span>
            <span style={{ flex: 1, minWidth: 0, overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' }}>
              ถามคลังความรู้: “{debouncedQuery.trim()}”
            </span>
            <span style={{ fontFamily: 'var(--vmx-mono)', fontSize: 10.5, color: 'var(--clr-ink-soft)', padding: '2px 6px', border: '1px solid var(--clr-border)', borderRadius: 4, whiteSpace: 'nowrap' }}>
              {coarsePointer ? 'แตะถาม' : view.askInFlow ? '↵' : 'ctrl ↵'}
            </span>
          </button>
        )}
        <ErrorBoundary fallback={null}>
          <AskAnswerCard ask={ask} onOpenWiki={handlersRef.current.onOpenWiki} onClose={onClose} />
        </ErrorBoundary>

        {/* Agentic action — the model picks from a validated catalog, the
            student confirms, the palette's own dispatch executes. */}
        {hasQuery && looksLikeAction(debouncedQuery.trim()) && !intents.length && (
          <button
            type="button"
            onClick={runAgent}
            className="vmx-omni-row"
            style={{
              all: 'unset', cursor: 'pointer', display: 'flex', alignItems: 'center', gap: 10,
              boxSizing: 'border-box', width: 'calc(100% - 24px)', margin: '8px 12px 0',
              padding: '10px 12px', minHeight: 44, borderRadius: 10,
              border: '1px dashed color-mix(in srgb, var(--clr-gold) 55%, var(--clr-border))',
              color: 'var(--clr-ink)', fontSize: 13,
            }}
          >
            <span aria-hidden="true" style={{ color: 'var(--clr-gold-text)' }}>⚡</span>
            <span style={{ flex: 1, minWidth: 0, overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' }}>
              สั่งให้จัดการ: “{debouncedQuery.trim()}”
            </span>
            <span style={{ fontFamily: 'var(--vmx-mono)', fontSize: 10.5, color: 'var(--clr-ink-soft)', padding: '2px 6px', border: '1px solid var(--clr-border)', borderRadius: 4, whiteSpace: 'nowrap' }}>
              {coarsePointer ? 'แตะสั่ง' : 'คลิก'}
            </span>
          </button>
        )}
        {agent?.phase === 'loading' && (
          <div className="vmx-omni-card" style={{ margin: '10px 12px 4px', padding: '12px 16px', display: 'flex', gap: 10, alignItems: 'center' }} aria-live="polite">
            <span className="vmx-omni-spark" aria-hidden="true" style={{ color: 'var(--clr-gold-text)' }}>⚡</span>
            <span style={{ fontSize: 13, color: 'var(--clr-ink-soft)' }}>กำลังอ่านคำสั่งและเทียบกับสิ่งที่แอปทำได้จริง…</span>
          </div>
        )}
        {(agent?.phase === 'refused' || agent?.phase === 'error') && (
          <div className="vmx-omni-card" style={{ margin: '10px 12px 4px', padding: '12px 16px' }}>
            <span style={{ fontSize: 13, color: 'var(--clr-ink-soft)' }}>{agent.message}</span>
          </div>
        )}
        {agent?.phase === 'confirm' && (
          <div className="vmx-omni-card" style={{ margin: '10px 12px 4px', padding: '14px 16px' }}>
            <div style={{ display: 'flex', alignItems: 'baseline', gap: 8, flexWrap: 'wrap' }}>
              <span aria-hidden="true" style={{ color: 'var(--clr-gold-text)' }}>⚡</span>
              <span style={{ fontSize: 13.5, lineHeight: 1.6 }}>{agent.say}</span>
            </div>
            <div style={{ display: 'flex', gap: 8, marginTop: 10 }}>
              <button type="button" onClick={() => executeAgent(agent.action)}
                style={{ font: 'inherit', fontSize: 12.5, fontWeight: 700, cursor: 'pointer', border: '1px solid var(--clr-border)', background: 'var(--clr-sage)', color: 'var(--clr-ink)', borderRadius: 8, padding: '7px 14px' }}>
                ทำเลย
              </button>
              <button type="button" onClick={() => setAgent(null)}
                style={{ font: 'inherit', fontSize: 12.5, cursor: 'pointer', border: '1px solid var(--clr-border)', background: 'var(--clr-surface-2)', color: 'var(--clr-ink)', borderRadius: 8, padding: '7px 14px' }}>
                ยกเลิก
              </button>
            </div>
          </div>
        )}

        {/* Answer cards — intent hits computed from real data */}
        {intents.map((intent) => (
          intent.kind === 'dose'
            ? <DoseCard key="dose" intent={intent} onOpenCalc={() => { try { window.dispatchEvent(new Event('vmx-open-vetcalc')); } catch { /* no-op */ } onClose(); }} />
            : <CourseCard key="course" intent={intent} onOpenLibraryShelf={openLibraryShelf} onPracticeSubject={practiceSubject} />
        ))}

        {/* Source status — what the index knows right now */}
        {!hasQuery && (
          <div style={{
            padding: '8px 20px',
            display: 'flex',
            gap: 8,
            flexWrap: 'wrap',
            alignItems: 'center',
            borderBottom: '1px solid var(--clr-border)',
            background: 'var(--clr-bg)',
          }}>
            <span style={{ fontFamily: 'var(--vmx-mono)', fontSize: 11, color: 'var(--clr-ink-soft)', padding: '2px 8px', border: '1px solid var(--clr-border)', borderRadius: 10 }}>
              {indexTotal.toLocaleString()} รายการในดัชนี
            </span>
            {OMNI_SOURCES.map((src) => {
              const st = sourceState[src.id];
              return (
                <span key={src.id} style={{ fontFamily: 'var(--vmx-mono)', fontSize: 11, color: 'var(--clr-ink-soft)', padding: '2px 8px', border: '1px solid var(--clr-border)', borderRadius: 10, display: 'inline-flex', gap: 5, alignItems: 'center' }}>
                  <span aria-hidden="true">{src.icon}</span>
                  {src.label}
                  {st?.status === 'loading' && ' กำลังโหลด…'}
                  {st?.status === 'ready' && ` ${st.entries.length.toLocaleString()}`}
                  {st?.status === 'error' && ' ออฟไลน์'}
                </span>
              );
            })}
          </div>
        )}

        {/* Results — grouped, streamed, keyboard-navigable across groups */}
        <div ref={listRef} style={{ maxHeight: '52vh', overflowY: 'auto', padding: 4 }}>
          {view.flat.filter((it) => it.type !== 'ask').length === 0 && !sourcesLoading && intents.length === 0 && !ask && (
            <div style={{ padding: '32px 20px', textAlign: 'center', color: 'var(--clr-ink-soft)', fontSize: 14 }}>
              {debouncedQuery.trim().length >= 8
                ? <>ไม่พบรายการที่ตรง — ลองถามคลังความรู้ด้านบนได้เลย</>
                : <>ไม่พบที่ตรงกับ "{query}"</>}
            </div>
          )}
          {view.sections.map((section) => (
            <div key={section.type}>
              <div style={{
                padding: '10px 16px 4px',
                fontSize: 11,
                fontFamily: 'var(--vmx-mono)',
                color: 'var(--clr-ink-soft)',
                textTransform: 'uppercase',
                letterSpacing: '0.1em',
                fontWeight: 600,
                display: 'flex',
                alignItems: 'baseline',
                gap: 6,
              }}>
                <span aria-hidden="true">{GROUP_META[section.type]?.icon}</span>
                {GROUP_META[section.type]?.label || section.type}
                <span style={{ fontWeight: 400 }}>{section.total.toLocaleString()}</span>
              </div>
              {section.items.map((item, iInGroup) => {
                const flatIdx = section.startIdx + iInGroup;
                const active = flatIdx === activeIdx;
                return (
                  <button
                    key={`${item.type}-${item.label}-${flatIdx}`}
                    data-flat-idx={flatIdx}
                    className="vmx-omni-row"
                    onClick={() => fire(item)}
                    onMouseEnter={() => setActiveIdx(flatIdx)}
                    style={{
                      all: 'unset',
                      cursor: 'pointer',
                      display: 'flex',
                      alignItems: 'center',
                      gap: 12,
                      width: '100%',
                      boxSizing: 'border-box',
                      padding: '9px 16px',
                      borderRadius: 8,
                      background: active ? 'var(--clr-surface-2)' : 'transparent',
                      transition: 'background 0.05s',
                      animationDelay: `${Math.min(iInGroup, 8) * 14}ms`,
                    }}
                  >
                    <span style={{ fontSize: 20, flex: '0 0 auto' }}>{item.icon}</span>
                    <div style={{ flex: 1, minWidth: 0 }}>
                      <div style={{
                        fontSize: 14,
                        fontWeight: 500,
                        color: 'var(--clr-ink)',
                        overflow: 'hidden',
                        textOverflow: 'ellipsis',
                        whiteSpace: 'nowrap',
                      }}>
                        <HighlightedLabel label={item.label} query={debouncedQuery} />
                      </div>
                      {item.hint && (
                        <div style={{
                          fontSize: 11,
                          color: 'var(--clr-ink-soft)',
                          fontFamily: 'var(--vmx-mono)',
                          marginTop: 2,
                          overflow: 'hidden',
                          textOverflow: 'ellipsis',
                          whiteSpace: 'nowrap',
                        }}>
                          {item.hint}
                        </div>
                      )}
                    </div>
                    {active && (
                      <span style={{ fontFamily: 'var(--vmx-mono)', fontSize: 11, color: 'var(--clr-ink-soft)', flex: '0 0 auto' }}>↵</span>
                    )}
                  </button>
                );
              })}
              {section.shown < section.total && (
                <button
                  type="button"
                  onClick={() => setExpandedGroups((prev) => new Set(prev).add(section.type))}
                  style={{
                    all: 'unset',
                    cursor: 'pointer',
                    display: 'block',
                    boxSizing: 'border-box',
                    width: '100%',
                    padding: '6px 16px 10px 48px',
                    fontSize: 12,
                    color: 'var(--clr-sage-text)',
                    fontWeight: 600,
                  }}
                >
                  แสดงเพิ่ม ({(section.total - section.shown).toLocaleString()} รายการ)
                </button>
              )}
            </div>
          ))}
          {sourcesLoading && (
            <div style={{ padding: '8px 16px 14px', display: 'flex', flexDirection: 'column', gap: 8 }} aria-label="กำลังโหลดแหล่งข้อมูล">
              {[0, 1, 2].map((i) => (
                <div key={i} style={{ display: 'flex', gap: 12, alignItems: 'center' }}>
                  <div className="vmx-omni-shimmer" style={{ width: 22, height: 22, borderRadius: 6 }} />
                  <div className="vmx-omni-shimmer" style={{ height: 12, flex: 1, maxWidth: 300 + i * 60 }} />
                </div>
              ))}
            </div>
          )}
        </div>

        {/* Footer */}
        <div style={{
          padding: '10px 16px',
          borderTop: '1px solid var(--clr-border)',
          background: 'var(--clr-bg)',
          fontFamily: 'var(--vmx-mono)',
          fontSize: 11,
          color: 'var(--clr-ink-soft)',
          display: 'flex',
          gap: 16,
          flexWrap: 'wrap',
        }}>
          <span>↑↓ เลื่อน</span>
          <span>↵ เลือก</span>
          <span>esc ปิด</span>
          <span>{coarsePointer ? 'แตะ ✦ เพื่อถาม' : 'ctrl ↵ ถามคลังความรู้'}</span>
          <span style={{ marginLeft: 'auto' }}>
            {hasQuery ? `${view.flat.length} ผลลัพธ์` : 'ดัชนีสร้างสดจากข้อมูลจริง'}
          </span>
        </div>
      </div>
    </div>
  );
}
