// Writes research/tests/fixtures/r/_serosurvey.R: per-farm COUNTS of the made-up serosurvey, the only
// part of it the R fixtures need (ICC and DEFF over 49 farms, Mantel-Haenszel with the farm as stratum).
// No row, name, phone number or date leaves the source file; only counts are written.
//
//   node research/scripts/r-parity/derive-serosurvey-counts.mjs [path to serosurvey-2569.csv]
//
// Default source: C:\Users\palmz\Desktop\vet-mock\work\research-studio\workspace\data\serosurvey-2569.csv
// (windows-874). The rules repeat work/research-studio/workspace/check.py, the independent program that
// reproduced numbers.json 47 of 47: Thai digits become Arabic; a two-digit year is Buddhist Era 25xx;
// BE years minus 543; age in whole months at sampling; missing birth dates are "ไม่ทราบ", "-", "" or
// "999"; the exposure is age >= 24 months among animals with a known age; positive = ELISA "บวก".
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = process.argv[2] || 'C:/Users/palmz/Desktop/vet-mock/work/research-studio/workspace/data/serosurvey-2569.csv';
const OUT = path.resolve(HERE, '..', '..', 'tests', 'fixtures', 'r', '_serosurvey.R');

const text = new TextDecoder('windows-874').decode(readFileSync(SRC));
const lines = text.split(/\r?\n/).filter((l) => l.length);
const head = lines[0].split(',');
const col = (name) => { const i = head.indexOf(name); if (i < 0) throw new Error(`no column ${name}`); return i; };
const C = { farm: col('ฟาร์ม'), sampled: col('วันที่เก็บตัวอย่าง'), born: col('วันเกิด'), elisa: col('ผล ELISA') };
const MISS = new Set(['ไม่ทราบ', '-', '', '999']);
const thaiDigits = (s) => s.replace(/[๐-๙]/g, (ch) => String(ch.charCodeAt(0) - 0x0e50));
function date(s) {
  const [d, m, y0] = thaiDigits(s.trim()).split('/');
  let y = Number(y0);
  if (y0.length === 2) y += 2500;
  return [y - 543, Number(m), Number(d)];
}

const farms = new Map();
for (const line of lines.slice(1)) {
  const r = line.split(',');
  const s = date(r[C.sampled]);
  const bornRaw = r[C.born];
  let age = null;
  if (!MISS.has(bornRaw.trim())) {
    const b = date(bornRaw);
    age = (s[0] - b[0]) * 12 + (s[1] - b[1]) - (s[2] < b[2] ? 1 : 0);
  }
  const f = r[C.farm];
  if (!farms.has(f)) farms.set(f, { n: 0, pos: 0, a: 0, b: 0, c: 0, d: 0 });
  const t = farms.get(f);
  const pos = r[C.elisa].trim() === 'บวก';
  t.n++; if (pos) t.pos++;
  if (age !== null) {
    if (age >= 24) { if (pos) t.a++; else t.b++; } else if (pos) t.c++; else t.d++;
  }
}
const ids = [...farms.keys()].sort();
const v = (k) => ids.map((f) => farms.get(f)[k]).join(', ');
const total = (k) => ids.reduce((s, f) => s + farms.get(f)[k], 0);
const out = `# GENERATED by research/scripts/r-parity/derive-serosurvey-counts.mjs from the made-up file
# work/research-studio/workspace/data/serosurvey-2569.csv (windows-874). Counts only, one entry per farm
# in farm-id order; no row of the file is copied. Totals: ${total('n')} cows, ${total('pos')} positive, ${ids.length} farms;
# known age ${total('a') + total('b') + total('c') + total('d')}: a ${total('a')}, b ${total('b')}, c ${total('c')}, d ${total('d')}.
# Exposure: age >= 24 months at sampling; outcome: ELISA positive (rules in the generator's header).
sero_farm <- c(${ids.map((f) => `"${f}"`).join(', ')})
sero_n <- c(${v('n')})
sero_pos <- c(${v('pos')})
sero_a <- c(${v('a')})
sero_b <- c(${v('b')})
sero_c <- c(${v('c')})
sero_d <- c(${v('d')})
`;
writeFileSync(OUT, out);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${ids.length} farms, ${total('n')} cows, ${total('pos')} positive, 2x2 [[${total('a')}, ${total('b')}], [${total('c')}, ${total('d')}]]`);
