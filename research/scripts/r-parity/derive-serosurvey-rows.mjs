// Writes research/tests/fixtures/r/_serosurvey_rows.R: the 728 rows of the made-up serosurvey reduced to the
// five numbers the M2 farm routes need (farm, ELISA positive, age in months, not vaccinated in the last 6
// months, herd size) [M2-DESIGN.md 3.2.2 robust, 3.3.4 survey]. No owner name, phone number, cow id or date
// is written; the age is whole months at sampling (the only use of the two dates).
//
//   node research/scripts/r-parity/derive-serosurvey-rows.mjs [path to serosurvey-2569.csv]
//
// Default source: research/tests/fixtures/serosurvey/serosurvey-2569.csv (windows-874, made-up data). The
// rules are derive-serosurvey-counts.mjs's (and work/research-studio/workspace/check.py's): Thai digits become
// Arabic; a two-digit year is Buddhist Era 25xx; BE years minus 543; age in whole months at sampling;
// missing birth dates are "ไม่ทราบ", "-", "" or "999"; positive = ELISA "บวก"; vacNo = 1 for "ไม่ฉีด"
// (not vaccinated), 0 for "ฉีด", missing for "ไม่ทราบ"; herd size from "ขนาดฝูง (ตัว)".
// The architect's M2 R run (work/loop-2026-09-26/research-m2/architect.md) used the same rows: 670 with a
// known age and vaccine answer, 728 in all, 49 farms.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = process.argv[2] || path.resolve(HERE, '..', '..', 'tests', 'fixtures', 'serosurvey', 'serosurvey-2569.csv');
const OUT = path.resolve(HERE, '..', '..', 'tests', 'fixtures', 'r', '_serosurvey_rows.R');

const text = new TextDecoder('windows-874').decode(readFileSync(SRC));
const lines = text.split(/\r?\n/).filter((l) => l.length);
const head = lines[0].split(',');
const col = (name) => { const i = head.indexOf(name); if (i < 0) throw new Error(`no column ${name}`); return i; };
const C = { farm: col('ฟาร์ม'), sampled: col('วันที่เก็บตัวอย่าง'), born: col('วันเกิด'), elisa: col('ผล ELISA'), vaccine: col('วัคซีนใน 6 เดือน'), herd: col('ขนาดฝูง (ตัว)') };
const VACCINE = { 'ไม่ฉีด': 1, 'ฉีด': 0, 'ไม่ทราบ': null };
const MISS = new Set(['ไม่ทราบ', '-', '', '999']);
const thaiDigits = (s) => s.replace(/[๐-๙]/g, (ch) => String(ch.charCodeAt(0) - 0x0e50));
function date(s) {
  const [d, m, y0] = thaiDigits(s.trim()).split('/');
  let y = Number(y0);
  if (y0.length === 2) y += 2500;
  return [y - 543, Number(m), Number(d)];
}

const rows = [];
for (const line of lines.slice(1)) {
  const r = line.split(',');
  const s = date(r[C.sampled]);
  let age = null;
  if (!MISS.has(r[C.born].trim())) {
    const b = date(r[C.born]);
    age = (s[0] - b[0]) * 12 + (s[1] - b[1]) - (s[2] < b[2] ? 1 : 0);
  }
  const vac = r[C.vaccine].trim();
  if (!(vac in VACCINE)) throw new Error(`unexpected vaccine answer ${vac}`);
  const herd = Number(thaiDigits(r[C.herd].trim()));
  if (!Number.isInteger(herd) || herd <= 0) throw new Error(`unexpected herd size ${r[C.herd]}`);
  rows.push({ farm: r[C.farm], pos: r[C.elisa].trim() === 'บวก' ? 1 : 0, age, vacNo: VACCINE[vac], herd });
}
const na = (v) => (v === null ? 'NA' : String(v));
const complete = rows.filter((r) => r.age !== null && r.vacNo !== null).length;
const out = `# GENERATED by research/scripts/r-parity/derive-serosurvey-rows.mjs from the made-up file
# research/tests/fixtures/serosurvey/serosurvey-2569.csv (windows-874). One entry per cow in file order, five
# numbers each: farm, ELISA positive (1/0), age in whole months at sampling (NA when the birth date is
# unknown), not vaccinated in the last 6 months (1 "ไม่ฉีด", 0 "ฉีด", NA "ไม่ทราบ"), herd size. No name,
# phone number, cow id or date. ${rows.length} cows, ${new Set(rows.map((r) => r.farm)).size} farms, ${complete} with a known age and vaccine answer.
sero_rows <- data.frame(
  farm = c(${rows.map((r) => `"${r.farm}"`).join(', ')}),
  pos = c(${rows.map((r) => r.pos).join(', ')}),
  age = c(${rows.map((r) => na(r.age)).join(', ')}),
  vacNo = c(${rows.map((r) => na(r.vacNo)).join(', ')}),
  herd = c(${rows.map((r) => r.herd).join(', ')}),
  stringsAsFactors = FALSE
)
`;
writeFileSync(OUT, out);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${rows.length} cows, ${complete} complete for the robust fixture`);
