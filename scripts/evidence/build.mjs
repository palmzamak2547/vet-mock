function pointPrompt(q, cands) {
  const opts = choices(q);
  const pages = cands.map((c, i) => `[P${i + 1}] ${c.p.doc.title} — page ${c.p.page.n}\n`
    + c.p.page.lines.slice(0, PAGE_LINES).map((l, k) => `L${k + 1}: ${l[4].slice(0, 200)}`).join('\n')).join('\n\n');
  const asked = q.type === 'tf'
    ? `Statement: ${wholeStem(q).slice(0, 900)}\nThe statement is ${q.answer ? 'TRUE' : 'FALSE'}.\n`
    : `Question: ${wholeStem(q).slice(0, 900)}\n${opts ? `Options:\n${opts.map((o, i) => `${LETTERS[i]}. ${o.slice(0, 300)}`).join('\n')}\n` : ''}`
      + `Correct answer: ${keyText(q).slice(0, 500)}\n`;
  const want = q.type === 'tf'
    ? `Find the ONE page whose lines show that. ${q.answer ? '' : 'For a false statement the lines must state the correct fact the statement gets wrong: a page that merely does not mention it does not count. '}`
    : 'Find the ONE page whose lines state the fact that makes the correct answer correct. ';
  return asked
    + `Our explanation: ${String(q.explain || '').slice(0, 500)}\n\n`
    + `Lecture pages, every line numbered:\n\n${pages}\n\n`
    + `${want}A page that only names the topic does not count.\n`
    + `Return {"page": "P2" or null, "lines": [line numbers, the fewest that carry the fact, at most ${MAX_LINES}], `
    + '"quote": "the exact words copied from those lines, in their own language, 40 words at most", '
    + '"strength": "states" | "partial" | "none", "contradicts": true | false}\n'
    + '"states": a student who reads only those lines can tell the correct answer is right. "partial": the lines give part of it, or only the topic. '
    + '"contradicts": true only when the page clearly says something that makes the correct answer wrong.';
}

function blindPrompt(q, lines) {
  const opts = choices(q);
  if (q.type === 'tf') {
    return `A lecture slide says:\n"""\n${lines.join('\n')}\n"""\n\nStatement: ${wholeStem(q).slice(0, 900)}\n\n`
      + 'Using ONLY what the slide lines say, with no outside knowledge: is the statement "true" (the lines say it), '
      + '"false" (the lines say something that contradicts it) or "undecided" (the lines do not settle it)? '
      + 'A statement the lines simply do not mention is undecided, never false. '
      + 'Return {"verdict": "true" | "false" | "undecided", "because": "the words of the slide that confirm or contradict it, copied exactly"}';
  }
  const head = `A lecture slide says:\n"""\n${lines.join('\n')}\n"""\n\nQuestion: ${wholeStem(q).slice(0, 900)}\n`;
  if (opts) {
    return `${head}Options:\n${opts.map((o, i) => `${i + 1}. ${o.slice(0, 300)}`).join('\n')}\n\n`
      + 'Using ONLY what the slide lines say, with no outside knowledge, which option is the answer? '
      + 'If the lines alone do not decide it, the option is null even when you know the answer from elsewhere. '
      + 'Return {"option": the number or null, "sure": true | false, "because": "the words of the slide that decide it, copied exactly"}';
  }
  return `${head}Proposed answer: ${keyText(q).slice(0, 500)}\n\n`
    + 'Using ONLY what the slide lines say, with no outside knowledge: do they state the proposed answer? '
    + 'Return {"states": true | false, "sure": true | false, "because": "the words of the slide that state it, copied exactly"}';
}

/** The page's heading: the largest text in its upper part; the first line of a page read only from a picture. */
export function headingOf(page) {
  let best = -1;
  page.lines.forEach((l, i) => {
    if (l[6] === 'v' || l[1] > 0.4 * page.h || l[4].length < 3) return;
    if (best < 0 || l[5] > page.lines[best][5] + 0.5) best = i;
  });
  return best < 0 && page.lines.length && page.lines.every((l) => l[6] === 'v') ? 0 : best;
}

/** The numbers a text prints, Thai digits read as Arabic and thousands separators dropped: "1,500 มก." → ["1500"]. */
export function numbersOf(text) {
  const plain = String(text || '').normalize('NFKC').replace(/[๐-๙]/g, (d) => String('๐๑๒๓๔๕๖๗๘๙'.indexOf(d)));
  return [...plain.matchAll(/\d+(?:,\d{3})*(?:\.\d+)?/g)].map((m) => m[0].replace(/,/g, ''));
}

/** The reader's reason must be words of the lines it was shown: an answer given from memory is not evidence. */
export function grounded(because, lines) {
  const want = squash(because);
  const text = squash(lines.join(' '));
  if (want.length < 6) return false;
  if (text.includes(want)) return true;
  let found = 0; let pieces = 0;
  for (let i = 0; i + 10 <= want.length; i += 5) { pieces++; if (text.includes(want.slice(i, i + 10))) found++; }
  return pieces >= 2 && found >= 0.8 * pieces;
}

/** The pointed lines, kept only when the copied words stand in them (else where on the page they do stand).
 *  The page's own text lines are tried before the lines read from its pictures: they carry exact boxes. */
export function settle(point, cands) {
  const c = cands[Number(String(point?.page || '').replace(/^P/i, '')) - 1];
  if (!c || !point.quote) return null;
  const all = c.p.page.lines;
  const given = [...new Set((point.lines || []).filter((n) => Number.isInteger(n) && n >= 1 && n <= all.length).map((n) => n - 1))].sort((a, b) => a - b);
  const own = all.map((_, i) => i).filter((i) => all[i][6] !== 'v');
  for (const view of own.length && own.length < all.length ? [own, all.map((_, i) => i)] : [all.map((_, i) => i)]) {
    const got = locate(point.quote, given.map((g) => view.indexOf(g)).filter((k) => k >= 0), view.map((i) => squash(all[i][4])));
    if (got) return { cand: c, idx: got.map((k) => view[k]) };
  }
  return null;
}

/** Where a copied quote stands among squashed lines: indices into `flat`, or null. */
function locate(quote, given, flat) {
  const want = squash(quote);
  if (want.length < 6) return null;
  const all = flat;
  const holds = (ids) => ids.length > 0 && ids.map((i) => flat[i]).join('').includes(want);
  const fits = (ids) => ids.length > 0 && ids.length <= MAX_LINES && ids[ids.length - 1] - ids[0] <= MAX_LINES + 4;
  if (holds(given) && fits(given)) return given;
  // Its lines hold its words in another order, or with a word mended: nine tenths of the quote's
  // overlapping twelve-letter pieces must stand in them.
  if (fits(given) && want.length >= 24) {
    const text = given.map((i) => flat[i]).join('');
    let found = 0; let pieces = 0;
    for (let i = 0; i + 12 <= want.length; i += 6) { pieces++; if (text.includes(want.slice(i, i + 12))) found++; }
    if (pieces >= 3 && found >= 0.9 * pieces) return given;
  }
  for (let n = 1; n <= MAX_LINES; n++) {   // the model miscounted: the shortest run of lines that holds its words
    for (let s = 0; s + n <= all.length; s++) {
      const run = Array.from({ length: n }, (_, k) => s + k);
      if (holds(run)) return run;
    }
  }
  // Words copied from several places with their bullets dropped: each piece must stand in a line, or in a run
  // of up to three lines when a sentence wraps. The run nearest the lines the model named is taken.
  const pieces = String(quote).split(/\s*(?:…|\.{3}|•|\n|\s\/\s|;|\|)\s*/).map(squash).filter((x) => x.length >= 6);
  if (!pieces.length) return null;
  const near = given.length ? given[0] : 0;
  const idx = new Set();
  for (const piece of pieces) {
    let best = null;
    for (let n = 1; n <= 3 && !best; n++) {
      for (let s = 0; s + n <= all.length; s++) {
        if (!flat.slice(s, s + n).join('').includes(piece)) continue;
        if (!best || Math.abs(s - near) < Math.abs(best[0] - near)) best = Array.from({ length: n }, (_, k) => s + k);
      }
    }
    if (!best) return null;
    for (const i of best) idx.add(i);
  }
  const ids = [...idx].sort((a, b) => a - b);
  return ids.length <= MAX_LINES + 2 ? ids : null;
}

/** Boxes of the chosen lines in thousandths of the page, lines that touch joined into one. */
export function boxesOf(page, idx) {
  const rects = idx.map((i) => page.lines[i].slice(0, 4)).sort((a, b) => a[1] - b[1]);
  const merged = [];
  for (const r of rects) {
    const m = merged[merged.length - 1];
    const lineH = r[3] - r[1];
    if (m && r[1] - m[3] < lineH * 0.9 && r[0] < m[2] + 4 && r[2] > m[0] - 4) {
      m[0] = Math.min(m[0], r[0]); m[2] = Math.max(m[2], r[2]); m[3] = Math.max(m[3], r[3]);
    } else merged.push([...r]);
  }
  // Each edge is brought inside the page first (a line may run a point past it), then the size is taken.
  const k = (v, of) => Math.max(0, Math.min(1000, Math.round((v / of) * 1000)));
  const pad = 3;
  return merged.map(([x0, y0, x1, y1]) => {
    const [a, b, c, d] = [k(x0 - pad, page.w), k(y0 - pad, page.h), k(x1 + pad, page.w), k(y1 + pad, page.h)];
    return [a, b, c - a, d - b];
  }).filter(([, , w, h]) => w > 0 && h > 0);
}

async function find(subject) {
  const docs = loadDocs(subject);
  const index = pageIndex(docs);
  const { questions, SOURCE_DOCS } = await finalPool(subject);
  const sourceDocs = SOURCE_DOCS.filter((d) => d.subject === subject);
  const byTopic = await topicDocs(subject, docs, questions, sourceDocs);
  const rows = [];
  let done = 0;
  await pool(questions, 8, async (item) => {
    const { q } = item;
    const cited = citedPages(item, sourceDocs, docs);
    const row = { v: FIND_V, qid: `${q.subject}:${q.id}`, id: q.id, subject, topic: q.topic, type: q.type || 'mcq', scope: item.scope,
      bankFile: item.bankFile, h: evidenceHash(q), cites: [...cited], state: 'none' };
    rows.push(row);
    const key = keyText(q);
    if (!key || q.type === 'match' || !index.n) { row.state = key ? 'no-pages' : 'no-key'; return; }
    const terms = await ask('deepseek-flash', 'You write search terms. Reply with JSON only.', termsPrompt(q), 300);
    const extra = [...(terms?.en || []), ...(terms?.th || [])].filter((t) => typeof t === 'string');
    const cands = candidatesFor(item, index, cited, extra, byTopic[q.topic]);
    if (!cands.length) { row.state = 'no-candidate'; return; }
    row.cands = cands.map((c) => c.id);
    const point = await ask(POINTER, 'You match an exam answer to the lecture lines that state it. Reply with JSON only.', pointPrompt(q, cands), 900);
    if (!point) { row.state = 'error'; return; }
    row.strength = point.strength;
    if (point.contradicts) row.contradicts = true;
    const got = point.strength === 'states' || point.contradicts ? settle(point, cands) : null;
    if (!got) {
      row.state = point.strength === 'states' ? 'quote-not-found' : (point.strength || 'none');
      if (point.quote) row.pointed = { page: point.page, lines: point.lines, quote: String(point.quote).slice(0, 300) };
      return;
    }
    const { cand } = got;
    let { idx } = got;
    const page = cand.p.page;
    const pictured = idx.some((i) => page.lines[i][6] === 'v');   // read from a picture: the whole slide, no highlight
    // A fact that leans on the slide's heading ("Mechanism: oxidize thiol" under "Halogen compound") is shown with
    // it: when the heading carries words of the key that the lines lack, the heading is marked too.
    const head = headingOf(page);
    let headText = head >= 0 && !idx.includes(head) ? page.lines[head][4] : '';
    if (headText && !pictured) {
      const inLines = new Set(idx.flatMap((i) => tokens(page.lines[i][4])));
      const inHead = new Set(tokens(headText));
      if (tokens(key).some((t) => !inLines.has(t) && inHead.has(t))) { idx = [head, ...idx].sort((a, b) => a - b); headText = ''; }
    }
    const lines = idx.map((i) => page.lines[i][4]);
    // What the reader is given: the lines, under the names of their document and slide, as a student sees them.
    const shown = [`(document: ${cand.p.doc.title})`, ...(headText ? [`(slide heading: ${headText})`] : []), ...lines];
    Object.assign(row, { sha16: cand.p.doc.sha16, page: page.n, w: page.w, h2: page.h, lines: idx,
      text: lines, quote: String(point.quote).slice(0, 300), boxes: pictured ? [] : boxesOf(page, idx), ...(pictured ? { pictured } : {}) });
    const blind = await ask(READER, 'You read a lecture slide and answer from it alone. Reply with JSON only.', blindPrompt(q, shown), 500);
    if (!blind) { row.state = 'error'; return; }
    const want = answerIndex(q);
    const sure = blind.sure !== false && grounded(blind.because, lines);
    if (NEGATIVE.test(q.q) || ALL_OF.test(keyText(q))) row.byExclusion = true;   // decided by what a list leaves out: sampled apart when checked
    if (q.type === 'tf') {
      row.blind = blind.verdict ?? null;
      const expected = q.answer ? 'true' : 'false';
      if (blind.verdict === expected && sure) row.state = point.contradicts ? 'review' : 'states';
      else if ((blind.verdict === 'true' || blind.verdict === 'false') && sure) row.state = 'conflict';
      else row.state = 'undecided';
    } else if (choices(q)) {
      row.blind = blind.option ?? null;
      if (blind.option === want + 1 && sure) row.state = point.contradicts ? 'review' : 'states';
      else if (Number.isInteger(blind.option) && blind.option !== want + 1 && sure) row.state = 'conflict';
      else row.state = 'undecided';
    } else {
      row.blind = blind.states ?? null;
      row.state = blind.states && sure ? (point.contradicts ? 'review' : 'states') : 'undecided';
    }
    // A number in the key that the lines do not print (a dose, a percentage, a duration) is the mismatch that
    // matters most: the slide may teach another figure. Such a row waits for a person, with the numbers named.
    const claim = q.type === 'mcq' ? key : (q.type === 'tf' && q.answer === true ? q.q : '');
    const missing = numbersOf(claim).filter((n) => !numbersOf(lines.join(' ')).includes(n));
    if (row.state === 'states' && missing.length) { row.state = 'review'; row.numbers = missing; }
    if (++done % 50 === 0) console.log(`  ${subject}: ${done} read`);
  });
  rows.sort((a, b) => a.id - b.id);
  fs.mkdirSync(path.join(DATA, 'registry'), { recursive: true });
  fs.writeFileSync(path.join(DATA, 'registry', `${subject}.jsonl`), `${rows.map((r) => JSON.stringify(r)).join('\n')}\n`);
  report(subject);
}

// ---------- the last reading: the slide as the student will see it ----------
// Nothing is published on the models' word alone. Each proposed slide is drawn with its highlight beside the
// question and its key (pages.py sheets), and looked at; the verdicts land in ROOT/checks.json:
//   { "<qid>": { "v": "ok" | "weak" | "wrong" | "key-doubt", "at": "<what was looked at>", "note": "..." } }
// A verdict holds only for the pick it was given on (`at`): a different page, other lines or an edited question
// puts the row back in the queue.
const PROPOSED = new Set(['states', 'review', 'conflict']);
const sigOf = (r) => `${r.sha16}:${r.page}:${r.h}:${crypto.createHash('sha1').update(JSON.stringify(r.boxes || [])).digest('hex').slice(0, 8)}`;

function registry(subject) {
  const file = path.join(DATA, 'registry', `${subject}.jsonl`);
  if (!fs.existsSync(file)) return [];
  const rows = fs.readFileSync(file, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
  const checks = readJson(path.join(DATA, 'checks.json'), {});
  for (const r of rows) {
    // A verdict follows the pick it was given on, whatever the models say on a later run: the eye outranks them.
    const c = r.sha16 ? checks[r.qid] : null;
    if (c && c.at === sigOf(r)) r.checked = c.v;
  }
  return rows;
}
/** What the app is given: a proposed slide that was looked at and found right. */
const published = (rows) => rows.filter((r) => r.checked === 'ok');

/** The proposed slides nobody has looked at yet, with what a sheet needs to draw them. */
async function tocheck(subject) {
  const rows = registry(subject).filter((r) => r.sha16 && PROPOSED.has(r.state) && !r.checked);
  const { questions } = await finalPool(subject);
  const bank = new Map(questions.map(({ q }) => [q.id, q]));
  const out = rows.map((r) => {
    const q = bank.get(r.id) || {};
    return { qid: r.qid, at: sigOf(r), type: r.type, state: r.state, sha16: r.sha16, page: r.page, boxes: r.boxes || [], pictured: Boolean(r.pictured),
      q: String(q.q || ''), key: q.type === 'tf' ? (q.answer ? 'TRUE' : 'FALSE') : keyText(q), numbers: r.numbers || null };
  });
  writeJson(path.join(DATA, 'work', `${subject}.tocheck.json`), out);
  console.log(`${subject}: ${out.length} proposed slides to look at`);
}

/** Take verdicts in: node build.mjs check --file verdicts.json   ([{ qid, verdict, note }])
 *  A verdict is recorded for the pick the sheet showed (the `at` that `tocheck` wrote), never for whatever the
 *  registry holds now: if `find` ran again in between and chose another page, the verdict matches nothing and
 *  the row simply waits for its next sheet. */
function check() {
  const verdicts = readJson(path.resolve(arg('file')), []);
  const file = path.join(DATA, 'checks.json');
  const checks = readJson(file, {});
  const drawn = new Map();
  let n = 0;
  for (const v of verdicts) {
    const subject = String(v.qid || '').split(':')[0];
    if (!drawn.has(subject)) drawn.set(subject, new Map(readJson(path.join(DATA, 'work', `${subject}.tocheck.json`), []).map((r) => [r.qid, r.at])));
    const at = drawn.get(subject).get(v.qid);
    if (!at || !['ok', 'weak', 'wrong', 'key-doubt'].includes(v.verdict)) continue;
    checks[v.qid] = { v: v.verdict, at, ...(v.note ? { note: String(v.note).slice(0, 240) } : {}) };
    n++;
  }
  writeJson(file, checks);
  console.log(`${n} of ${verdicts.length} verdicts recorded`);
}

function report(subject) {
  const rows = registry(subject);
  const by = {};
  for (const r of rows) by[r.state] = (by[r.state] || 0) + 1;
  const shown = published(rows).length;
  const waiting = rows.filter((r) => r.sha16 && PROPOSED.has(r.state) && !r.checked).length;
  const turned = rows.filter((r) => r.checked && r.checked !== 'ok').length;
  console.log(`${subject}: ${rows.length} questions, ${shown} with a slide (${Math.round((100 * shown) / Math.max(1, rows.length))}%), `
    + `${waiting} proposed and not looked at yet, ${turned} looked at and turned down  ${JSON.stringify(by)}`);
  // The questions that already cite a library page are the yardstick: was that page read, and was it the one picked?
  const known = rows.filter((r) => r.cites?.length);
  const near = (r) => r.cites.some((id) => { const [sha, n] = id.split(':'); return sha === r.sha16 && Math.abs(Number(n) - r.page) <= 1; });
  const read = known.filter((r) => r.cands?.some((id) => r.cites.includes(id)));
  const picked = known.filter((r) => r.sha16);
  console.log(`  cite a library page: ${known.length}; that page was read for ${read.length}; a slide was picked for ${picked.length}: `
    + `${picked.filter(near).length} on the cited page or the one beside it, ${picked.filter((r) => r.cites.some((id) => id.startsWith(r.sha16))).length} in the cited document`);
}

// ---------- the index the app reads ----------
async function index(subject) {
  const rows = published(registry(subject));
  const cat = readJson(path.join(DATA, 'catalog.json'), []);
  const docs = [];
  const q = {};
  for (const r of rows) {
    const c = cat.find((d) => d.sha16 === r.sha16);
    if (!c) continue;
    let di = docs.findIndex((d) => d[0] === r.sha16);
    if (di < 0) di = docs.push([r.sha16, c.slug, c.title, c.kind]) - 1;
    q[r.id] = [di, r.page, Math.round(r.w), Math.round(r.h2), r.boxes, r.h];
  }
  const dir = path.join(REPO, 'src/data/evidence');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${subject}.generated.js`);
  // A subject with nothing published has no file: the app then asks for nothing on its questions.
  if (Object.keys(q).length) fs.writeFileSync(file, `${GENERATED}export const EVIDENCE = ${JSON.stringify({ docs, q })};\n`);
  else fs.rmSync(file, { force: true });
  writeLoaders(dir);
  console.log(`${subject}: ${Object.keys(q).length} questions on ${new Set(rows.map((r) => `${r.sha16}:${r.page}`)).size} pages of ${docs.length} documents`);
}

/** One lazy import per subject that has a file: the map src/lib/evidence.js loads from. */
export function writeLoaders(dir) {
  const subjects = fs.readdirSync(dir).filter((f) => f.endsWith('.generated.js') && f !== 'loaders.generated.js').map((f) => f.slice(0, -'.generated.js'.length)).sort();
  const rows = subjects.map((s) => `  '${s}': () => import('./${s}.generated.js'),\n`).join('');
  fs.writeFileSync(path.join(dir, 'loaders.generated.js'), `${GENERATED}export const EVIDENCE_LOADERS = {\n${rows}};\n`);
}

async function upload(subject) {
  const { execFileSync } = await import('node:child_process');
  const rows = published(registry(subject));
  const pages = [...new Map(rows.map((r) => [`${r.sha16}:${r.page}`, { sha16: r.sha16, page: r.page }])).values()]
    .filter((p) => /^[0-9a-f]{16}$/.test(p.sha16) && Number.isInteger(p.page) && p.page > 0);
  const list = path.join(DATA, 'work', `${subject}.render.json`);
  writeJson(list, pages);
  execFileSync('python', ['-I', path.join(REPO, 'scripts/evidence/pages.py'), 'render', '--data', DATA, '--pages', list], { stdio: 'inherit' });
  const { CLOUDFLARE_API_TOKEN: token, R2_ACCOUNT_ID: account } = process.env;
  if (!token || !account) throw new Error('set CLOUDFLARE_API_TOKEN and R2_ACCOUNT_ID (.r2env) to upload');
  // The folder name is the grant (api/evidence-pass.js hands it to members): it lives in ROOT, never in the repository.
  const folder = (process.env.VMX_EVIDENCE_FOLDER || fs.readFileSync(path.join(DATA, 'folder.txt'), 'utf8')).trim();
  if (!/^[0-9a-f]{32}$/.test(folder)) throw new Error('ROOT/folder.txt must hold the 32 hex characters of the image folder');
  const sent = readJson(path.join(DATA, 'uploaded.json'), {});
  let n = 0;
  // The admin page's status row reads this file to tell that the folder answers (api/_lib/system-status.js).
  if (!sent[`e/${folder}/ok.txt`]) {
    const res = await fetch(`https://api.cloudflare.com/client/v4/accounts/${account}/r2/buckets/${BUCKET}/objects/e/${folder}/ok.txt`, {
      method: 'PUT', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'text/plain', 'Cache-Control': 'no-store' }, body: 'ok',
    });
    if (res.ok) sent[`e/${folder}/ok.txt`] = 'ok';
  }
  await pool(pages, 6, async (p) => {
    const name = `p${String(p.page).padStart(3, '0')}.webp`;
    const key = `e/${folder}/${p.sha16}/${name}`;
    const file = path.join(DATA, 'img', p.sha16, name);
    if (!fs.existsSync(file)) return;
    const body = fs.readFileSync(file);
    const sum = crypto.createHash('sha1').update(body).digest('hex');
    if (sent[key] === sum) return;
    for (let attempt = 0; attempt < 4; attempt++) {
      const res = await fetch(`https://api.cloudflare.com/client/v4/accounts/${account}/r2/buckets/${BUCKET}/objects/${key}`, {
        method: 'PUT', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'image/webp', 'Cache-Control': 'public, max-age=31536000, immutable' }, body,
      });
      if (res.ok) { sent[key] = sum; n++; return; }
      if (attempt === 3) console.log(`  ${p.sha16}/${name} answered ${res.status}`);
      await sleep(2000 * (attempt + 1));
    }
  });
  writeJson(path.join(DATA, 'uploaded.json'), sent);
  console.log(`${subject}: ${n} page images uploaded, ${pages.length} cited in all`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  assertPrivateRoot();
  const cmd = process.argv[2];
  const subjects = (arg('subject') || '').split(',').filter(Boolean);
  const run = { find, report, tocheck, index, upload }[cmd];
  if (cmd === 'catalog') await catalog();
  else if (cmd === 'check' && arg('file')) check();
  else if (run && subjects.length) for (const s of subjects) await run(s);
  else { console.error('usage: node scripts/evidence/build.mjs catalog | find|report|tocheck|index|upload --subject <id,..> | check --file <verdicts.json>'); process.exit(1); }
}
