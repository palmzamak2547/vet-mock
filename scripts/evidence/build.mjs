const seg = new Intl.Segmenter('th', { granularity: 'word' });
const STOP = new Set(('the and of in with for is are to by on at as or from which that this be not no an a its it was were has have can may than '
  + 'ที่ และ ใน ของ เป็น การ มี ได้ ให้ จาก หรือ กับ ว่า คือ โดย จะ ไม่ ข้อใด ข้อ ใด อะไร อย่างไร ต่อไปนี้ ดังนี้ ซึ่ง นี้ นั้น แต่ เพื่อ ด้วย ถูกต้อง ถูก ผิด').split(' '));
export function tokens(text) {
  const out = [];
  for (const { segment, isWordLike } of seg.segment(String(text || '').toLowerCase())) {
    if (!isWordLike) continue;
    let t = segment;
    if (/^[a-z]/.test(t)) {
      if (t.length < 2) continue;
      if (t.length > 4 && t.endsWith('s') && !t.endsWith('ss') && !t.endsWith('us') && !t.endsWith('is')) t = t.slice(0, -1);
    } else if (/^[0-9]/.test(t)) t = t.replace(/,/g, '');
    else if (t.length < 2) continue;
    if (!STOP.has(t)) out.push(t);
  }
  return out;
}
/** Letters and digits only: a copied quote is compared without spaces, bullets or punctuation. */
export const squash = (s) => String(s || '').normalize('NFC').toLowerCase().replace(/[^\p{L}\p{N}\p{M}]+/gu, '');

