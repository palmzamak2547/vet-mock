/** A registered source document that is a library file: its name pattern reads the library title and an edition has its page count. */
function libraryOf(sourceDoc, docs) {
  const hits = docs.filter((d) => (sourceDoc.match.test(d.title) || sourceDoc.match.test(d.title.replace(/\s*\([^)]*\)\s*$/, '')))
    && sourceDoc.editions.some((e) => e.pages === d.pageCount));
  return hits.length === 1 ? hits[0] : null;
}

// ---------- candidates ----------
function loadDocs(subject) {
  const rows = readJson(path.join(DATA, 'catalog.json'), []).filter((r) => r.subject === subject && KINDS.has(r.kind));
  const docs = [];
  for (const r of rows) {
    const d = readJson(path.join(DATA, 'pages', `${r.sha16}.json`));
    if (!d) continue;
    for (const p of d.pages) {
      // Words a vision model read from the page's pictures (pages.py vision) follow the page's own lines, marked 'v':
      // they can be pointed at, and a slide matched through them is shown whole, with no highlight to misplace.
      const read = (p.vlines || []).map((l) => [...l.slice(0, 6), 'v']);
      if (read.length) { p.lines = [...(p.ok ? p.lines : []), ...read]; p.ok = true; }
    }
    docs.push({ ...d, kind: r.kind, year: r.academic_year });
  }
  return docs;
}

function pageIndex(docs) {
  const pages = [];
  const df = new Map();
  for (const d of docs) {
    for (const p of d.pages) {
      if (!p.ok || p.lines.length < 2) continue;
      const tf = new Map();
      for (const l of p.lines) for (const t of tokens(l[4])) tf.set(t, (tf.get(t) || 0) + 1);
      if (tf.size < 4) continue;
      for (const t of tf.keys()) df.set(t, (df.get(t) || 0) + 1);
      pages.push({ doc: d, page: p, tf, len: [...tf.values()].reduce((a, b) => a + b, 0) });
    }
  }
  const avg = pages.reduce((a, p) => a + p.len, 0) / Math.max(1, pages.length);
  return { pages, df, avg, n: pages.length };
}

/** The library pages a question already cites, as "sha16:page". */
function citedPages(item, sourceDocs, docs) {
  const out = new Set();
  for (const c of item.cites) {
    const sd = c.slug && sourceDocs.find((d) => d.slug === c.slug);
    const lib = sd && libraryOf(sd, docs);
    if (lib && c.page) out.add(`${lib.sha16}:${c.page}`);
  }
  return out;
}

function candidatesFor(item, index, cited, extra, topicShas) {
  const { q } = item;
  const weights = new Map();
  const add = (text, w) => { for (const t of tokens(text)) weights.set(t, Math.max(weights.get(t) || 0, w)); };
  add(wholeStem(q), 1);
  add(String(q.explain || '').slice(0, 600), 1.2);
  add((q.keywords || []).join(' '), 2.5);
  add((extra || []).join(' '), 2.5);   // the same fact in the slide's own words, Thai and English
  add(keyText(q), 3);
  const scored = [];
  for (const p of index.pages) {
    let s = 0;
    for (const [t, w] of weights) {
      const f = p.tf.get(t);
      if (!f) continue;
      const idf = Math.log(1 + (index.n - index.df.get(t) + 0.5) / (index.df.get(t) + 0.5));
      s += (w * idf * (f * 2.2)) / (f + 1.2 * (0.25 + (0.75 * p.len) / index.avg));
    }
    if (topicShas?.has(p.doc.sha16)) s *= 1.6;   // the deck this topic is taught from
    const id = `${p.doc.sha16}:${p.page.n}`;
    if (s > 0 || cited.has(id)) scored.push({ id, p, s, cited: cited.has(id) });
  }
  scored.sort((a, b) => b.s - a.s);
  const top = scored.slice(0, CANDIDATES);
  const missing = scored.filter((x) => x.cited && !top.includes(x)).slice(0, 2);
  for (let i = 0; i < missing.length && top.length; i++) top[top.length - 1 - i] = missing[i];   // a cited page is always read
  return top;
}

/** Which library documents each topic is taught from: the documents its questions cite, and a model's reading of
 *  the topic names against the document titles and first pages. Kept in ROOT/topics/<subject>.json for a person to read. */
async function topicDocs(subject, docs, questions, sourceDocs) {
  const { SUBJECTS } = await imp('src/data/curriculum.js');
  const topics = (SUBJECTS.find((s) => s.id === subject)?.topics || []).map((t) => ({ id: t.id, label: t.label, lecturer: t.lecturer || '' }));
  const map = Object.fromEntries(topics.map((t) => [t.id, new Set()]));
  for (const item of questions) {
    for (const id of citedPages(item, sourceDocs, docs)) map[item.q.topic]?.add(id.split(':')[0]);
  }
  const listing = docs.map((d, i) => `D${i + 1}: ${d.title} [${d.kind}, ${d.pageCount} pages] `
    + d.pages.slice(0, 2).flatMap((p) => p.lines.slice(0, 6).map((l) => l[4])).join(' | ').slice(0, 260)).join('\n');
  const out = await ask(READER, 'You file lecture documents under course topics. Reply with JSON only.',
    `Course topics:\n${topics.map((t) => `${t.id}: ${t.label} (${t.lecturer})`).join('\n')}\n\nDocuments:\n${listing}\n\n`
    + 'For each topic, list the documents that teach it (a document may serve several topics; a topic may have none; a syllabus or schedule serves none). '
    + 'Return {"<topic id>": ["D3", ...], ...} with every topic id as a key.', 3000);
  for (const [t, list] of Object.entries(out || {})) {
    for (const d of Array.isArray(list) ? list : []) {
      const doc = docs[Number(String(d).replace(/^D/i, '')) - 1];
      if (doc && map[t]) map[t].add(doc.sha16);
    }
  }
  writeJson(path.join(DATA, 'topics', `${subject}.json`), { topics,
    map: Object.fromEntries(Object.entries(map).map(([t, set]) => [t, [...set]])),
    titles: Object.fromEntries(docs.map((d) => [d.sha16, d.title])) });
  return map;
}

