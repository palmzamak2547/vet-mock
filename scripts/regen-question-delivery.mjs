#!/usr/bin/env node
// Generate the fail-closed question delivery gate.
//
// A question that explicitly requires a figure but has no figure cannot be
// answered as written. Keep it in the source bank for repair/provenance, but
// exclude it from counts and runtime pools until the asset is attached.

import fs from 'node:fs';
import path from 'node:path';
import { bankFiles, readBank } from './lib/bank-file.mjs';
import { needsFigure } from './lib/question-standard.mjs';

const OUT = 'src/data/question-delivery.generated.js';
const CHECK = process.argv.includes('--check');

const blocked = [];
for (const file of bankFiles()) {
  const { questions } = await readBank(file);
  for (const q of questions) {
    let reason = null;
    if (needsFigure(q)) {
      reason = 'ต้องใช้ภาพประกอบ แต่ยังไม่มีภาพที่ตรวจสอบแล้ว';
    } else {
      const image = q.image || q.imagePath;
      if (typeof image === 'string' && image.startsWith('/')) {
        const diskPath = path.join('public', image.replace(/^\//, ''));
        if (!fs.existsSync(diskPath)) reason = 'อ้างภาพประกอบที่ไม่มีไฟล์ในระบบ';
      }
    }
    if (!reason) continue;
    blocked.push({
      key: `${q.subject}:${q.id}`,
      reason,
      source: path.basename(file),
    });
  }
}

blocked.sort((a, b) => a.key.localeCompare(b.key));
const lines = [
  '// AUTO-GENERATED by scripts/regen-question-delivery.mjs - do not hand-edit.',
  '// Questions stay in source banks for repair, but never enter learner pools.',
  '',
  `export const BLOCKED_QUESTIONS = ${JSON.stringify(blocked, null, 2)};`,
  '',
  'const BLOCKED_KEYS = new Set(BLOCKED_QUESTIONS.map((item) => item.key));',
  '',
  "export const questionDeliveryKey = (question) => `${question?.subject || ''}:${question?.id ?? ''}`;",
  'export const isQuestionDeliverable = (question) => !BLOCKED_KEYS.has(questionDeliveryKey(question));',
  `export const BLOCKED_QUESTION_COUNT = ${blocked.length};`,
  '',
];
const output = lines.join('\n');

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== output) {
    console.error(`✗ ${OUT} ไม่ตรงกับคลังโจทย์ปัจจุบัน - รัน npm run regen:delivery`);
    process.exit(1);
  }
  console.log(`✓ question delivery gate ตรงกัน: ปิดไว้ ${blocked.length} ข้อ`);
} else {
  fs.writeFileSync(OUT, output, 'utf8');
  console.log(`✓ wrote ${OUT}: ปิดไว้ ${blocked.length} ข้อจนกว่าจะมีภาพที่ตรวจสอบแล้ว`);
}
