#!/usr/bin/env node
// ============================================================
// regen-note-source-titles.mjs — regenerate src/data/note-source-titles.generated.js
// ============================================================
// The notes reader shows a section's source line through noteSourceLabel
// (src/lib/source-label.js). A file name that a document registered in
// src/data/source-docs.js claims is shown as that document's title. The
// registry itself cannot ship: it is 78 KB and its patterns use regex
// lookbehind, which iOS 14 cannot parse (tests/unit/no-lookbehind.test.mjs).
// So this script asks the registry once, for every file-style name the notes
// actually use, and keeps only the answers: { "Name as stored": "Title" }.
//
// Usage:
//   node scripts/regen-note-source-titles.mjs           # rewrite the module
//   node scripts/regen-note-source-titles.mjs --check   # exit 1 when stale
//
// tests/unit/notes-source-label.test.mjs fails when the checked-in copy is
// stale, so a new notes file that cites a registered document is caught.
// ============================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { sameGenerated } from './lib/same-generated.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
export const OUT = path.join(root, 'src/data/note-source-titles.generated.js');

/** The registered title of the first document whose pattern claims `name`, or null. */
export function registeredTitleFor(name, docs) {
  for (const doc of docs) {
    if (!doc.match) continue;
    doc.match.lastIndex = 0;
    if (doc.match.test(name)) return doc.title;
  }
  return null;
}

export function renderNoteSourceTitles(titles) {
  const keys = Object.keys(titles).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const rows = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(titles[k])},`).join('\n');
  return [
    '// ============================================================',
    '// note-source-titles.generated.js — DO NOT EDIT BY HAND',
    '// ============================================================',
    '// Generated by scripts/regen-note-source-titles.mjs: the registered title of',
    '// each file name the notes cite that a document in source-docs.js claims.',
    '// Regenerate with: node scripts/regen-note-source-titles.mjs',
    '// ============================================================',
    '',
    'export const NOTE_SOURCE_TITLES = {',
    rows,
    '};',
    '',
  ].join('\n');
}

export async function generateNoteSourceTitles() {
  const { NOTE_SOURCES } = await import(pathToFileURL(path.join(root, 'src/data/note-corpus.js')).href);
  const { noteFileNames } = await import(pathToFileURL(path.join(root, 'src/lib/source-label.js')).href);
  const { SOURCE_DOCS } = await import(pathToFileURL(path.join(root, 'src/data/source-docs.js')).href);
  const titles = {};
  const walk = (x) => {
    if (!x || typeof x !== 'object') return;
    if (typeof x.source === 'string') {
      for (const name of noteFileNames(x.source.replace(/\s*·\s*/g, ', '))) {
        const title = registeredTitleFor(name, SOURCE_DOCS);
        if (title) titles[name] = title;
      }
    }
    for (const v of Object.values(x)) if (v && typeof v === 'object') walk(v);
  };
  for (const sources of Object.values(NOTE_SOURCES)) for (const s of sources) walk(await s.load());
  return renderNoteSourceTitles(titles);
}

const invokedDirectly = process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (invokedDirectly) {
  const body = await generateNoteSourceTitles();
  const rel = path.relative(root, OUT);
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (!sameGenerated(current, body)) {
      console.error(`${rel} is stale; run: node scripts/regen-note-source-titles.mjs`);
      process.exit(1);
    }
    console.log(`${rel} matches the notes and source-docs.js`);
    process.exit(0);
  }
  if (sameGenerated(current, body)) {
    console.log(`${rel} already current`);
  } else {
    fs.writeFileSync(OUT, body);
    console.log(`wrote ${rel}`);
  }
}
