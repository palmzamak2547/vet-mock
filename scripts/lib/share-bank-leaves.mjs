// The text of api/_lib/share-bank.generated.js. Pure: the caller hands in the
// questions and the rules (scripts/regen-share-bank.mjs passes the real ones,
// the unit tests pass small ones).

import { compareKeys, leafLines, LEAF_LAYOUT_NOTE } from './merge-friendly.mjs';

const toRuns = (ids) => {
  const runs = [];
  for (const id of [...ids].sort((a, b) => a - b)) {
    const last = runs[runs.length - 1];
    if (last && id === last[1] + 1) last[1] = id;
    else runs.push([id, id]);
  }
  return runs;
};

/**
 * @param {any[]} questions
 * @param {{
 *   shareSubjects: string[],
 *   subjectName: (subject: string) => string | undefined,
 *   questionTopicId: (q: any) => string,
 *   isQuestionDeliverable: (q: any) => boolean,
 *   customRange: [number, number],
 * }} rules
 * @returns {{ text: string, subjects: Set<string>, ids: number, runs: number }}
 */
export function renderShareBank(questions, rules) {
  const byTopic = new Map();
  const perSubject = new Map();
  for (const q of questions) {
    const id = Number(q.id);
    if (!q.subject || !Number.isInteger(id) || id < 1 || !rules.isQuestionDeliverable(q)) continue;
    if (id >= rules.customRange[0] && id <= rules.customRange[1]) continue;
    const topic = rules.questionTopicId(q);
    const key = JSON.stringify([q.subject, topic]);
    if (!byTopic.has(key)) byTopic.set(key, { subject: q.subject, topic, ids: new Set() });
    byTopic.get(key).ids.add(id);
    if (!perSubject.has(q.subject)) perSubject.set(q.subject, new Set());
    perSubject.get(q.subject).add(id);
  }

  const L = [];
  L.push('// ============================================================');
  L.push('// share-bank.generated.js — AUTO-GENERATED by scripts/regen-share-bank.mjs, do NOT hand-edit');
  L.push('// ============================================================');
  L.push('// Per subject of SHARE_SUBJECTS: its name and the ids the bank has, as');
  L.push('// [first, last] runs of consecutive ids, held-back questions left out.');
  L.push('// Read by api/s.js only.');
  L.push(...LEAF_LAYOUT_NOTE);
  L.push('// ============================================================');
  L.push('');
  L.push('// Every subject a /s/ link can name, in SHARE_SUBJECTS order, with its name.');
  L.push('const NAMES = {');
  for (const subject of rules.shareSubjects) {
    L.push(...leafLines([subject], `${JSON.stringify(subject)}: ${JSON.stringify(rules.subjectName(subject) || subject)}`));
  }
  L.push('};');
  L.push('');
  L.push("// [subject, topic, that topic's ids as [first, last] runs, a lone id as itself]");
  L.push('const LEAVES = [');
  const leaves = [...byTopic.values()]
    .filter((l) => rules.shareSubjects.includes(l.subject))
    .sort((a, b) => compareKeys([a.subject, a.topic], [b.subject, b.topic]));
  for (const leaf of leaves) {
    L.push(...leafLines([leaf.subject, leaf.topic], JSON.stringify([leaf.subject, leaf.topic, toRuns(leaf.ids).map(([a, b]) => (a === b ? a : [a, b]))])));
  }
  L.push('];');
  L.push('');
  L.push('// One subject\'s runs: its topics\' runs, sorted and joined where they touch.');
  L.push('const runsBySubject = new Map();');
  L.push('for (const [subject, , runs] of LEAVES) {');
  L.push('  if (!runsBySubject.has(subject)) runsBySubject.set(subject, []);');
  L.push("  for (const run of runs) runsBySubject.get(subject).push(typeof run === 'number' ? [run, run] : run);");
  L.push('}');
  L.push('const joined = (runs) => {');
  L.push('  const out = [];');
  L.push('  for (const [first, last] of [...runs].sort((a, b) => a[0] - b[0])) {');
  L.push('    const prev = out[out.length - 1];');
  L.push('    if (prev && first <= prev[1] + 1) prev[1] = Math.max(prev[1], last);');
  L.push('    else out.push([first, last]);');
  L.push('  }');
  L.push('  return out;');
  L.push('};');
  L.push('');
  L.push('export const SHARE_BANK = Object.fromEntries(Object.entries(NAMES).map(([subject, name]) => [');
  L.push('  subject, { name, runs: joined(runsBySubject.get(subject) || []) },');
  L.push(']));');
  L.push('');

  let ids = 0;
  let runs = 0;
  for (const subject of rules.shareSubjects) {
    const set = perSubject.get(subject) || new Set();
    ids += set.size;
    runs += toRuns(set).length;
  }
  return { text: L.join('\n'), subjects: new Set(perSubject.keys()), ids, runs };
}
