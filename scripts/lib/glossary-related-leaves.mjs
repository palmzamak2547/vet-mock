// The text of src/data/glossary-related.generated.js. Pure: the caller hands in
// the glossary, the questions and the rules (scripts/regen-glossary-related.mjs
// passes the real ones, the unit tests pass small ones).
//
// A leaf is one glossary entry's related ids within one subject and topic, so
// two pull requests that add questions to different topics change different
// lines and merge by themselves. GLOSSARY_RELATED[entry] is every leaf of the
// entry in file order, joined when the module loads.

import { compareKeys, leafLines, LEAF_LAYOUT_NOTE } from './merge-friendly.mjs';

const escapeRegex = (s) => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * @param {any[]} glossary entries, in glossary order
 * @param {any[]} questions in bank order
 * @param {{
 *   entryKey: (entry: any) => string,
 *   searchableStrings: (entry: any) => string[],
 *   isQuestionDeliverable: (q: any) => boolean,
 *   questionTopicId: (q: any) => string,
 * }} rules
 * @returns {{ text: string, entries: number, links: number }}
 */
export function renderGlossaryRelated(glossary, questions, rules) {
  const leaves = [];
  let entries = 0;
  let links = 0;
  for (const entry of glossary) {
    const needles = rules.searchableStrings(entry)
      .map((s) => s.toLowerCase())
      .sort((a, b) => b.length - a.length);
    if (!needles.length) continue;
    const re = new RegExp(`(^|[^A-Za-z0-9])(${needles.map(escapeRegex).join('|')})(?![A-Za-z0-9])`, 'i');
    const scope = entry.__scope;
    const byTopic = new Map();
    for (const q of questions) {
      if (!q || q.id == null || !rules.isQuestionDeliverable(q)) continue;
      // A card scoped to one discipline must not offer another discipline's
      // questions — that is the same wrong-sense mistake one step later.
      if (scope !== 'universal' && !scope.has(q.subject)) continue;
      const blobs = [q.q, q.explain, ...(Array.isArray(q.options) ? q.options : [])];
      if (!blobs.some((b) => b && re.test(String(b)))) continue;
      const where = [q.subject ?? null, rules.questionTopicId(q)];
      const key = JSON.stringify(where);
      if (!byTopic.has(key)) byTopic.set(key, { where, ids: [] });
      byTopic.get(key).ids.push(q.id);
      links += 1;
    }
    if (!byTopic.size) continue;
    entries += 1;
    const term = rules.entryKey(entry);
    for (const { where, ids } of [...byTopic.values()].sort((a, b) => compareKeys(a.where, b.where))) {
      leaves.push([term, ...where, ids]);
    }
  }

  const L = [
    '// AUTO-GENERATED by scripts/regen-glossary-related.mjs — do not edit.',
    '// Question ids that mention each glossary entry, counted against the',
    '// whole bank so the number on the card is the same every time it opens.',
    ...LEAF_LAYOUT_NOTE,
    '',
    '// Each glossary entry\'s key, then its leaves: the ids of one subject and',
    '// topic, in bank order. A leaf\'s subject and topic are named by its header',
    '// and footer lines only, which the build strips.',
    'const LEAVES = [',
  ];
  // An entry's key opens its group and a comment closes it, so a new entry
  // and a new leaf at the end of the entry before it never meet on one line.
  let current = null;
  for (const [term, subject, topic, ids] of leaves) {
    if (term !== current) {
      if (current !== null) L.push(` // end of ${JSON.stringify(current)}`);
      L.push(` ${JSON.stringify(term)},`);
    }
    current = term;
    L.push(...leafLines([term, subject, topic], JSON.stringify(ids), ' '));
  }
  if (current !== null) L.push(` // end of ${JSON.stringify(current)}`);
  L.push('];');
  L.push('');
  L.push('export const GLOSSARY_RELATED = {};');
  L.push('let entry = null;');
  L.push("for (const item of LEAVES) if (typeof item === 'string') entry = item; else (GLOSSARY_RELATED[entry] ||= []).push(...item);");
  L.push('');
  return { text: L.join('\n'), entries, links };
}
