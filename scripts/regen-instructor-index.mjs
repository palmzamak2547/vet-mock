#!/usr/bin/env node
// ============================================================
// regen-instructor-index.mjs — regenerate src/data/instructor-index.generated.js
// ============================================================
// Why this file exists:
//   The topic screen asks one thing of the faculty directory: does this
//   lecturer string name a person with a profile? The search palette asks for
//   names to match. Both imported src/data/instructors.js, so both downloaded
//   the whole directory: 1,188 KB of JavaScript (300 KB gzip, measured on the
//   10 Nov 2026 build), 828 KB of it the publication lists that only an open
//   profile shows. Every device paid that on its first topic screen.
//
//   This script keeps what those two screens read: the names a lecturer string
//   is matched against, and the few words a search row prints and matches.
//   The directory itself now arrives with the profile (InstructorProfile.jsx).
//
// Usage:
//   node scripts/regen-instructor-index.mjs           # rewrite the module
//   node scripts/regen-instructor-index.mjs --check   # exit 1 when stale
//
// Run it after scripts/generate-instructor-directory.mjs changes the
// directory; `npm run lint:data` fails when the checked-in copy is stale.
// ============================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { sameGenerated } from './lib/same-generated.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
export const OUT = path.join(root, 'src/data/instructor-index.generated.js');

// In this order in every row. `slug` finds the full record; the names and
// aliases are what a lecturer string is matched against (instructor-lookup.js);
// the rest is what CommandPalette prints or searches.
export const INDEX_FIELDS = ['slug', 'nameEn', 'nameTh', 'nickname', 'aliases', 'position', 'areas', 'subjects'];

const empty = (value) => value == null || value === '' || (Array.isArray(value) && value.length === 0);

/** One slim row per directory entry, in the directory's own order. */
export function buildInstructorIndex(directory) {
  return directory.map((instructor) => {
    const row = {};
    for (const field of INDEX_FIELDS) {
      if (!empty(instructor[field])) row[field] = instructor[field];
    }
    return row;
  });
}

export function renderInstructorIndex(index) {
  return `// ============================================================
// INSTRUCTOR_INDEX — who has a profile, without the profiles
// ============================================================
//
// AUTO-GENERATED by scripts/regen-instructor-index.mjs from
// src/data/instructors-directory.js. Do NOT hand-edit; run
// \`npm run regen:instructor-index\`. \`npm run lint:data\` fails when stale.
//
// One row per person, in the directory's order: the slug, the names a
// lecturer string is matched against, and what a search row shows. Papers,
// sources and contact details stay in the directory, which loads only when a
// profile opens. Read it through src/data/instructor-index.js.
// ============================================================

export const INSTRUCTOR_INDEX = [
${index.map((row) => `  ${JSON.stringify(row)},`).join('\n')}
];
`;
}

/** The module text a fresh generation writes. */
export async function generateInstructorIndex() {
  const { INSTRUCTOR_DIRECTORY } = await import(pathToFileURL(path.join(root, 'src/data/instructors-directory.js')).href);
  return renderInstructorIndex(buildInstructorIndex(INSTRUCTOR_DIRECTORY));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const fresh = await generateInstructorIndex();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (!sameGenerated(current, fresh)) {
      console.error('instructor-index.generated.js is stale. Run: npm run regen:instructor-index');
      process.exit(1);
    }
    console.log('instructor-index.generated.js is current');
  } else {
    fs.writeFileSync(OUT, fresh);
    console.log(`wrote ${path.relative(root, OUT)} (${(Buffer.byteLength(fresh) / 1024).toFixed(0)} KB)`);
  }
}
