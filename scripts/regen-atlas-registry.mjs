import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { sameGenerated } from './lib/same-generated.mjs';
import { buildLabelRegistry } from './lib/atlas-label-registry.mjs';

const dir = resolve('public/atlas');
const models = {};
const labels = {};
for (const file of readdirSync(dir).filter(name => name.endsWith('-provenance.json')).sort()) {
  const proof = JSON.parse(readFileSync(resolve(dir, file), 'utf8'));
  if (!proof.id || !proof.profiles) continue;
  models[proof.id] = {
    poster: proof.poster,
    profiles: Object.fromEntries(Object.entries(proof.profiles).map(([id, profile]) => [id, {
      model: profile.model, bytes: profile.bytes, sha256: profile.sha256,
      triangles: profile.parts.reduce((sum, part) => sum + part.triangles, 0),
    }])),
    parts: proof.profiles.quick.parts.map(part => ({ id: part.id, originalName: part.originalName })),
  };
  const authoredPath = resolve('scripts/atlas-labels', `${proof.id}.json`);
  if (existsSync(authoredPath)) {
    Object.assign(labels, buildLabelRegistry(proof, JSON.parse(readFileSync(authoredPath, 'utf8'))));
  }
}
const assetsOutput = `// Generated by scripts/regen-atlas-registry.mjs. Edit source geometry and its conversion ledger.\nexport const ATLAS_ASSETS = Object.freeze(${JSON.stringify(models, null, 2)});\n`;
const labelsOutput = `// Generated by scripts/regen-atlas-registry.mjs. Edit scripts/atlas-labels/<specimen>.json and re-run.\nexport const ATLAS_LABELS = Object.freeze(${JSON.stringify(labels, null, 2)});\n`;
const assetsPath = resolve('src/data/atlas-assets.generated.js');
const labelsPath = resolve('src/data/atlas-labels.generated.js');
if (process.argv.includes('--check')) {
  if (!sameGenerated(readFileSync(assetsPath, 'utf8'), assetsOutput)) throw new Error('Atlas asset registry is stale.');
  if (!sameGenerated(readFileSync(labelsPath, 'utf8'), labelsOutput)) throw new Error('Atlas label registry is stale.');
} else {
  writeFileSync(assetsPath, assetsOutput);
  writeFileSync(labelsPath, labelsOutput);
}
console.log(`Atlas registry: ${Object.keys(models).length} specimens, ${Object.keys(labels).length} labeled.`);
