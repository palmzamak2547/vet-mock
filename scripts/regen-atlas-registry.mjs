import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const dir = resolve('public/atlas');
const models = {};
for (const file of readdirSync(dir).filter(name => name.endsWith('-provenance.json')).sort()) {
  const proof = JSON.parse(readFileSync(resolve(dir, file), 'utf8'));
  if (!proof.id || !proof.profiles) continue;
  models[proof.id] = {
    poster: proof.poster,
    profiles: Object.fromEntries(Object.entries(proof.profiles).map(([id, profile]) => [id, {
      model: profile.model, bytes: profile.bytes, sha256: profile.sha256,
      triangles: profile.parts.reduce((sum, part) => sum + part.triangles, 0),
    }])),
    parts: proof.profiles.quick.parts.map(part => ({ id: part.id, originalName: part.originalName })),
  };
}
const output = `// Generated by scripts/regen-atlas-registry.mjs. Edit source geometry and its conversion ledger.\nexport const ATLAS_ASSETS = Object.freeze(${JSON.stringify(models, null, 2)});\n`;
const path = resolve('src/data/atlas-assets.generated.js');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('Atlas asset registry is stale.');
} else writeFileSync(path, output);
console.log(`Atlas registry: ${Object.keys(models).length} specimens.`);
