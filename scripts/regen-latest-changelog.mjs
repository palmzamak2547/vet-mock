#!/usr/bin/env node
// ============================================================
// regen-latest-changelog.mjs — regenerate src/data/latest-changelog.generated.js
// ============================================================
// Why this file exists:
//   HomeView and Sidebar only ever render the NEWEST release (the
//   announcement banner and the sidebar badge), yet importing
//   LATEST_CHANGELOG from changelog.js keeps every historical entry in the
//   entry chunk — Rollup cannot tree-shake `CHANGELOG[0]` away from the
//   array it is read from. That was ~110 KB of source (100+ releases) on
//   every first paint, for one entry.
//
//   This script copies the newest entry and the scope labels into a small
//   module the entry chunk imports instead. changelog.js stays the one place
//   a release is written; the generated file is derived from it.
//
// Usage:
//   node scripts/regen-latest-changelog.mjs           # rewrite the module
//   node scripts/regen-latest-changelog.mjs --check   # exit 1 when stale
//
// `npm run build` and `npm run dev` regenerate it first, so a forgotten
// regen cannot ship a stale banner; lint:changelog-latest guards the
// checked-in copy.
// ============================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const out = path.join(root, 'src/data/latest-changelog.generated.js');

const { CHANGELOG, SCOPE_LABELS } = await import(pathToFileURL(path.join(root, 'src/data/changelog.js')).href);
const latest = CHANGELOG[0];
if (!latest?.version || !Array.isArray(latest.changes)) {
  console.error('changelog.js: CHANGELOG[0] is not a release entry');
  process.exit(1);
}

const body = `// ============================================================
// LATEST_CHANGELOG — the newest release, for the banner and the badge
// ============================================================
//
// AUTO-GENERATED by scripts/regen-latest-changelog.mjs — do NOT hand-edit.
// Write releases in src/data/changelog.js as before; \`npm run build\` and
// \`npm run dev\` regenerate this file, \`npm run regen:changelog\` does it
// by hand, and lint:changelog-latest fails when it is stale.
//
// HomeView and Sidebar import from here so the entry chunk carries one
// release entry instead of the whole history.
// ============================================================

export const SCOPE_LABELS = ${JSON.stringify(SCOPE_LABELS, null, 2)};

export const LATEST_CHANGELOG = ${JSON.stringify(latest, null, 2)};
`;

const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (current !== body) {
    console.error(`❌ ${path.relative(root, out)} is stale — run: npm run regen:changelog`);
    process.exit(1);
  }
  console.log(`✅ ${path.relative(root, out)} matches changelog.js (${latest.version})`);
  process.exit(0);
}
if (current === body) {
  console.log(`${path.relative(root, out)} already current (${latest.version})`);
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote ${path.relative(root, out)} (${latest.version})`);
}
