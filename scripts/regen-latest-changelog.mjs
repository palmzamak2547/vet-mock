#!/usr/bin/env node
// ============================================================
// regen-latest-changelog.mjs — gather the changelog into its generated modules
// ============================================================
// A release is written as one file, src/data/changelog/<version>.js
// (`npm run release:new` makes it). Releases before the files existed stay in
// src/data/changelog.js as written. Every release used to edit the top of
// changelog.js, the generated banner module and package.json's version, so
// any two releases in flight conflicted; one file per release does not.
//
// This script writes two modules, both gitignored because they are derived:
//   src/data/changelog-releases.generated.js  the release files, imported
//                                            (changelog-all.js merges them
//                                            with the history)
//   src/data/latest-changelog.generated.js    the newest release and the scope
//                                            labels, for the entry chunk
//                                            (HomeView, Sidebar, Landing,
//                                            client diagnostics), so it
//                                            carries one release, not 100+
//
// Usage:
//   node scripts/regen-latest-changelog.mjs           # write both modules
//   node scripts/regen-latest-changelog.mjs --check   # validate the releases
//
// `npm run build`, `npm run dev` and the unit suite (its --import setup) write
// them first. --check (lint:changelog-latest) writes nothing: every release
// file is named by its version, every version appears once, and every entry
// has a date, a headline and changes.
// ============================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { sameGenerated } from './lib/same-generated.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const releasesDir = path.join(root, 'src/data/changelog');
const outReleases = path.join(root, 'src/data/changelog-releases.generated.js');
const outLatest = path.join(root, 'src/data/latest-changelog.generated.js');

const parse = (v) => String(v).split('.').map((n) => Number.parseInt(n, 10) || 0);
export const compareVersions = (a, b) => {
  const x = parse(a);
  const y = parse(b);
  for (let i = 0; i < Math.max(x.length, y.length); i++) {
    const d = (x[i] || 0) - (y[i] || 0);
    if (d) return d;
  }
  return 0;
};

export function releaseFiles(dir = releasesDir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => /\.js$/.test(f)).sort((a, b) => compareVersions(b.slice(0, -3), a.slice(0, -3)));
}

/** The history in changelog.js, the release files, and every problem with them. */
export async function readChangelog(dir = releasesDir) {
  const { CHANGELOG: history, SCOPE_LABELS } = await import(pathToFileURL(path.join(root, 'src/data/changelog.js')).href);
  const problems = [];
  const releases = [];
  for (const file of releaseFiles(dir)) {
    const entry = (await import(pathToFileURL(path.join(dir, file)).href)).default;
    if (`${entry?.version}.js` !== file) problems.push(`src/data/changelog/${file}: version is ${entry?.version}, the file must be named <version>.js`);
    releases.push(entry);
  }
  const all = [...releases, ...history].sort((a, b) => compareVersions(b.version, a.version));
  const seen = new Set();
  for (const e of all) {
    if (!/^\d+\.\d+\.\d+$/.test(e?.version || '')) problems.push(`release ${e?.version}: version must be x.y.z`);
    if (seen.has(e.version)) problems.push(`release ${e.version} appears twice (run npm run release:new for a free number)`);
    seen.add(e.version);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(e.date || '') || !e.headline || !Array.isArray(e.changes) || !e.changes.length) {
      problems.push(`release ${e.version}: needs date (YYYY-MM-DD), headline and at least one change`);
    }
  }
  return { history, releases, all, files: releaseFiles(dir), SCOPE_LABELS, problems };
}

const HEADER = (what) => `// ============================================================
// AUTO-GENERATED by scripts/regen-latest-changelog.mjs — do NOT hand-edit, not committed.
// ${what}
// Write a release with \`npm run release:new\` (src/data/changelog/<version>.js).
// ============================================================
`;

/** Write a file only when its text changed, through a rename, so parallel callers never see half a file. */
function put(file, body) {
  try { if (sameGenerated(fs.readFileSync(file, 'utf8'), body)) return false; } catch { /* missing */ }
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, body);
  try { fs.renameSync(tmp, file); } catch (error) {
    fs.rmSync(tmp, { force: true });
    if (!sameGenerated(fs.readFileSync(file, 'utf8'), body)) throw error;
  }
  return true;
}

export async function writeChangelogModules() {
  // A draft (empty headline) still builds; lint:changelog-latest is what refuses it.
  const { all, files, SCOPE_LABELS } = await readChangelog();
  const names = files.map((f, i) => `r${i}`);
  const releasesBody = `${HEADER('The release files in src/data/changelog/, newest first.')}
${files.map((f, i) => `import ${names[i]} from './changelog/${f}';`).join('\n')}

export const RELEASES = [${names.join(', ')}];
`;
  const latestBody = `${HEADER('The newest release and the scope labels, so the entry chunk carries one release.')}
export const SCOPE_LABELS = ${JSON.stringify(SCOPE_LABELS, null, 2)};

export const LATEST_CHANGELOG = ${JSON.stringify(all[0], null, 2)};
`;
  return { wrote: [put(outReleases, releasesBody), put(outLatest, latestBody)], latest: all[0].version };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (process.argv.includes('--check')) {
    const { all, files, problems } = await readChangelog();
    if (problems.length) {
      for (const p of problems) console.error(`❌ ${p}`);
      process.exit(1);
    }
    console.log(`✅ changelog: ${all.length} releases (${files.length} release files), newest ${all[0].version}`);
  } else {
    const { wrote, latest } = await writeChangelogModules();
    console.log(`changelog modules ${wrote.some(Boolean) ? 'written' : 'already current'} (newest ${latest})`);
  }
}
