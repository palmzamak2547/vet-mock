#!/usr/bin/env node
// ============================================================
// regen-notes-registry.mjs — which subjects actually have notes
// ============================================================
// Usage:
//   node scripts/regen-notes-registry.mjs           # write
//   node scripts/regen-notes-registry.mjs --check   # fail if stale
//
// `has_notes` used to be hand-set in curriculum.js. It was true on three
// subjects while notes existed for twelve, and it is the flag the home screen
// uses to decide whether a subject with no questions is still worth opening —
// so a stale flag hides a subject that has content. Deriving it removes the
// hand-maintenance, and --check in lint:all stops it drifting again.
//
// The source of truth is the import list in NotesView, which is what a student
// actually reaches. Reading it textually rather than importing the corpus keeps
// this script cheap and avoids pulling megabytes of notes into a lint run.
// ============================================================

import fs from 'node:fs';

const OUT = 'src/data/notes-registry.generated.js';
const CHECK = process.argv.includes('--check');

const view = fs.readFileSync('src/views/NotesView.jsx', 'utf8');

// Both maps in NotesView: the lecture-derived corpus and the Vet 85 summaries.
const subjects = new Set();
for (const block of ['const NOTES_BY_SUBJECT = {', 'const NOTES_85_BY_SUBJECT = {']) {
  const start = view.indexOf(block);
  if (start === -1) continue;
  const body = view.slice(start + block.length, view.indexOf('\n};', start));
  for (const m of body.matchAll(/^\s*'?([\w-]+)'?\s*:/gm)) subjects.add(m[1]);
}

const list = [...subjects].sort();

// Which notes module each subject reads from, recovered by pairing the map
// entries with NotesView's own imports. Used to enumerate topics from the
// notes themselves rather than from the wiki.
const moduleOf = new Map();
for (const [, konst, file] of view.matchAll(/import \{ (NOTES_[A-Z0-9_]+) \} from '\.\.\/data\/(notes-[^']+)'/g)) {
  moduleOf.set(konst, file);
}
const notesFileOf = new Map();
for (const block of ['const NOTES_BY_SUBJECT = {', 'const NOTES_85_BY_SUBJECT = {']) {
  const start = view.indexOf(block);
  if (start === -1) continue;
  const body = view.slice(start + block.length, view.indexOf('\n};', start));
  for (const m of body.matchAll(/^\s*'?([\w-]+)'?\s*:\s*(NOTES_[A-Z0-9_]+)/gm)) {
    const file = moduleOf.get(m[2]);
    if (file) notesFileOf.set(`${m[1]}::${m[2]}`, file);
  }
}
// Topic-level availability is read from the notes modules themselves. It used
// to come from the wiki's governed registry, which agreed for every subject
// then in the app because all of them were governed — but a subject can have
// notes and not yet be governed, and that one reported zero topics and told
// students "ยังไม่มี Notes ในวิชานี้" while its notes sat in the bundle.
const topicRowSet = new Map();
for (const [key, file] of notesFileOf) {
  const subject = key.split('::')[0];
  const mod = await import(`../src/data/${file}`);
  const konst = key.split('::')[1];
  for (const topic of Object.keys(mod[konst] || {})) topicRowSet.set(`${subject}/${topic}`, { subject, topic });
}
const topicRows = [...topicRowSet.values()]
  .map(({ subject, topic }) => ({ subject, topic }))
  .sort((a, b) => a.subject.localeCompare(b.subject) || a.topic.localeCompare(b.topic));
const topicKeys = topicRows.map(({ subject, topic }) => `${encodeURIComponent(subject)}/${encodeURIComponent(topic)}`);
const topicCounts = Object.fromEntries(list.map((subject) => [
  subject,
  topicRows.filter((row) => row.subject === subject).length,
]));
const body = `// ============================================================
// notes-registry.generated.js — DO NOT EDIT BY HAND
// ============================================================
// Generated by scripts/regen-notes-registry.mjs from NotesView's own import
// maps, so "this subject has notes" can never disagree with what NotesView
// will actually render. Regenerate with: npm run regen:notes-registry
// ============================================================

/** Subject ids that have at least one notes topic. */
export const SUBJECTS_WITH_NOTES = new Set(${JSON.stringify(list, null, 2)});

/** Canonical subject/topic ids with at least one readable notes section. */
export const NOTE_TOPIC_KEYS = new Set(${JSON.stringify(topicKeys, null, 2)});

/** Number of readable note topics per subject. */
export const NOTE_TOPIC_COUNTS_BY_SUBJECT = Object.freeze(${JSON.stringify(topicCounts, null, 2)});

export function noteTopicKey(subjectId, topicId) {
  return \`${'${encodeURIComponent(subjectId)}/${encodeURIComponent(topicId)}'}\`;
}

export function hasNotes(subjectId) {
  return SUBJECTS_WITH_NOTES.has(subjectId);
}

export function hasNoteTopic(subjectId, topicId) {
  return NOTE_TOPIC_KEYS.has(noteTopicKey(subjectId, topicId));
}
`;

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current.trim() !== body.trim()) {
    console.log('❌ notes-registry.generated.js is stale — run: npm run regen:notes-registry');
    process.exit(1);
  }
  console.log(`✅ notes-registry.generated.js is up to date (${list.length} subjects with notes).`);
  process.exit(0);
}

fs.writeFileSync(OUT, body);
console.log(`✓ ${list.length} subjects / ${topicRows.length} topics with notes → ${OUT}`);
console.log(`  ${list.join(', ')}`);
