import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { CORRECTIONS } from '../src/lib/vetwiki/corrections.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(root, 'src', 'lib', 'vetwiki', 'conflict-summary.generated.js');
const counts = {};

for (const [key, notes] of Object.entries(CORRECTIONS)) {
  const parts = String(key).split('--');
  if (parts.length < 3 || !Array.isArray(notes) || notes.length === 0) continue;
  const topicId = `${parts[0]}--${parts[1]}`;
  counts[topicId] = (counts[topicId] || 0) + notes.length;
}

const ordered = Object.fromEntries(Object.entries(counts).sort(([a], [b]) => a.localeCompare(b)));
const body = `// Generated by scripts/regen-conflict-summary.mjs — do not edit by hand.\n`
  + `export const VETWIKI_CONFLICT_COUNTS = Object.freeze(${JSON.stringify(ordered, null, 2)});\n\n`
  + `export function conflictCountFor(subject, topic) {\n`
  + `  return VETWIKI_CONFLICT_COUNTS[\`${'${subject}'}--${'${topic}'}\`] || 0;\n`
  + `}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = await fs.readFile(outPath, 'utf8'); } catch {}
  if (current !== body) {
    console.error('conflict-summary.generated.js is stale — run npm run regen:conflict-summary');
    process.exitCode = 1;
  } else {
    console.log(`conflict summary is current (${Object.keys(ordered).length} topics)`);
  }
} else {
  await fs.writeFile(outPath, body, 'utf8');
  console.log(`wrote ${path.relative(root, outPath)} (${Object.keys(ordered).length} topics)`);
}
