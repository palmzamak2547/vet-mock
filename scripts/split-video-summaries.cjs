#!/usr/bin/env node
/**
 * split-video-summaries.cjs
 *
 * Splits the monolithic src/data/video-summaries.js (62k lines / ~2.2MB)
 * into per-subject files so VideoView lazy-loads only the subject the
 * user is currently watching.
 *
 * Strategy:
 *   1. Read video-summaries.js as text.
 *   2. Walk top-level entries by detecting `  <key>: {` lines at
 *      exactly 2-space indent. Each entry runs until the next entry's
 *      header line OR the closing `};` of the parent object.
 *   3. Parse each entry's `subject: 'X'` field to determine which
 *      bucket it goes in.
 *   4. Write src/data/video-summaries-<subject>.js for each bucket as
 *      `export const VIDEO_SUMMARIES_<SUBJECT> = { ...entries };`
 *   5. Replace src/data/video-summaries.js with a barrel that
 *      re-exports a merged VIDEO_SUMMARIES (so any existing consumer
 *      still works) PLUS a per-subject lazy loader the new VideoView
 *      path can call.
 *
 * Run:    node scripts/split-video-summaries.cjs
 *
 * Idempotent: safe to re-run; output files are overwritten.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src/data/video-summaries.js');
const OUT_DIR = path.join(ROOT, 'src/data');

if (!fs.existsSync(SRC)) {
  console.error('video-summaries.js missing at', SRC);
  process.exit(1);
}

const text = fs.readFileSync(SRC, 'utf8');
const lines = text.split('\n');

// Find the line that opens the object literal.
const openIdx = lines.findIndex((l) => /^export const VIDEO_SUMMARIES\s*=\s*\{/.test(l));
if (openIdx < 0) {
  console.error('Could not find `export const VIDEO_SUMMARIES = {`');
  process.exit(1);
}

// Capture the file header (comments + import lines before openIdx)
const headerLines = lines.slice(0, openIdx);

// Top-level entries: lines where indent === 2 spaces and look like
// `  <key>: {`. Key can be unquoted, single-quoted, or double-quoted.
// Two-space indent is critical — deeper indents are nested.
const ENTRY_HEAD = /^  (?:'([A-Za-z0-9_-]+)'|"([A-Za-z0-9_-]+)"|([A-Za-z_][A-Za-z0-9_-]*)):\s*\{\s*$/;

// Walk lines after openIdx, find each entry header and its end.
// End of entry = the line that has `^  \},?$` (2-space indent close)
// because the entry body uses ≥4-space indent.
const entries = []; // { key, startLine, endLine, body }
let i = openIdx + 1;
while (i < lines.length) {
  const headMatch = lines[i].match(ENTRY_HEAD);
  if (headMatch) {
    const key = headMatch[1] || headMatch[2] || headMatch[3];
    const startLine = i;
    // Find matching close at 2-space indent
    let j = i + 1;
    while (j < lines.length) {
      if (/^  \},?\s*$/.test(lines[j])) break;
      j++;
    }
    if (j >= lines.length) {
      console.error('Unclosed entry starting at line', i + 1, 'key', key);
      process.exit(2);
    }
    entries.push({ key, startLine, endLine: j, raw: lines.slice(startLine, j + 1).join('\n') });
    i = j + 1;
  } else if (/^\};?\s*$/.test(lines[i])) {
    // End of VIDEO_SUMMARIES object
    break;
  } else {
    i++;
  }
}

console.log(`Found ${entries.length} entries`);

// Extract subject field from each entry body.
// Match `subject: 'X'` or `subject: "X"` at any indent inside the entry.
const SUBJECT_RE = /\bsubject:\s*['"]([A-Za-z0-9_-]+)['"]/;

const bySubject = {};
let withoutSubject = 0;
for (const e of entries) {
  const m = e.raw.match(SUBJECT_RE);
  const subj = m ? m[1] : 'unknown';
  if (!m) withoutSubject++;
  (bySubject[subj] = bySubject[subj] || []).push(e);
}

console.log('Subject distribution:');
for (const [s, list] of Object.entries(bySubject).sort((a, b) => b[1].length - a[1].length)) {
  console.log(`  ${s}: ${list.length} entries`);
}
if (withoutSubject) {
  console.warn(`⚠️  ${withoutSubject} entries without subject field → bucketed as 'unknown'`);
}

// Generate per-subject files
const subjFileNames = {};
for (const [subj, list] of Object.entries(bySubject)) {
  const slug = subj.toLowerCase().replace(/[^a-z0-9-]/g, '-');
  const fileName = `video-summaries-${slug}.js`;
  const filePath = path.join(OUT_DIR, fileName);
  const constName = `VIDEO_SUMMARIES_${slug.toUpperCase().replace(/-/g, '_')}`;
  const body = [
    '// ============================================================',
    `// VIDEO SUMMARIES — subject="${subj}" (${list.length} entries)`,
    '// ============================================================',
    '// Auto-generated by scripts/split-video-summaries.cjs.',
    '// DO NOT hand-edit — re-run the script after updating',
    '// the original video-summaries.js.',
    '// ============================================================',
    '',
    `export const ${constName} = {`,
    list.map((e) => e.raw).join('\n'),
    '};',
    '',
  ].join('\n');
  fs.writeFileSync(filePath, body, 'utf8');
  subjFileNames[subj] = { file: fileName, constName, count: list.length };
  console.log(`  → wrote ${fileName} (${list.length} entries)`);
}

// Generate the new barrel: video-summaries.js
// IMPORTANT: NO top-level static imports of per-subject files —
// that would pull all of them into the barrel's chunk, defeating
// the split. All access is via dynamic import inside the loader.
const subjects = Object.keys(subjFileNames).sort();

const barrel = `// ============================================================
// VIDEO SUMMARIES — lazy barrel (auto-generated)
// ============================================================
// The data lives in per-subject files (video-summaries-<subject>.js).
// This barrel provides a per-subject lazy loader:
//
//   import { loadVideoSummariesForSubject } from './video-summaries.js';
//   const map = await loadVideoSummariesForSubject('com4');
//   const entry = map[videoId];
//
// Each call dynamic-imports ONE subject's chunk (~50-200 KB gzip
// instead of 870 KB for the old monolithic file). Cached per
// subject so subsequent calls return the same Promise.
//
// Legacy consumers that need cross-subject merged map should call
// \`loadAllVideoSummaries()\` — it triggers all dynamic imports in
// parallel and merges. Same total weight as before, but at least
// callers opt in explicitly.
//
// Regenerate via: node scripts/split-video-summaries.cjs
// ============================================================

const _lazyLoaders = {
${subjects
  .map((s) => `  '${s}': () => import('./${subjFileNames[s].file}').then((m) => m.${subjFileNames[s].constName}),`)
  .join('\n')}
};

const _subjectCache = new Map();

/**
 * Lazy-load all video summaries for one subject. Returns a flat
 * \`{ videoId: entry }\` map. Idempotent + cached.
 *
 * @param {string} subject — curriculum subject id (e.g. 'com4')
 * @returns {Promise<Record<string, object>>}
 */
export function loadVideoSummariesForSubject(subject) {
  if (!subject) return Promise.resolve({});
  if (_subjectCache.has(subject)) return _subjectCache.get(subject);
  const loader = _lazyLoaders[subject];
  if (!loader) return Promise.resolve({});
  const p = loader().catch((err) => {
    _subjectCache.delete(subject); // allow retry
    throw err;
  });
  _subjectCache.set(subject, p);
  return p;
}

let _allPromise = null;
/**
 * Load EVERY subject's summaries in parallel and return the merged
 * flat \`{ videoId: entry }\` map. Use only when you need cross-
 * subject lookup (rare). Pulls the full ~870 KB gzip total.
 *
 * @returns {Promise<Record<string, object>>}
 */
export function loadAllVideoSummaries() {
  if (_allPromise) return _allPromise;
  _allPromise = Promise.all(
    Object.values(_lazyLoaders).map((fn) => fn().catch(() => ({})))
  )
    .then((maps) => Object.assign({}, ...maps))
    .catch((err) => {
      _allPromise = null;
      throw err;
    });
  return _allPromise;
}
`;

fs.writeFileSync(SRC, barrel, 'utf8');
console.log(`  → rewrote video-summaries.js as barrel`);

console.log('Done.');
