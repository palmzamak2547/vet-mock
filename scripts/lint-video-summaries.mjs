#!/usr/bin/env node
/**
 * lint-video-summaries.mjs
 *
 * Checks the things a reader cannot check for themselves.
 *
 * A summary is study material a student answers an exam from, so the failure
 * that matters is not an ugly heading — it is a confident sentence the
 * recording never supported. Most of that can only be caught by reading, but
 * some of it leaves a mechanical trace, and that is what this gate looks for:
 *
 *   • a timestamp past the end of the recording (invented section)
 *   • a duration that disagrees with the transcript
 *   • a videoId that does not match the file it lives in
 *   • an examFormat asserted for a recording that never mentions the exam
 *   • text that refers to how the summary was produced
 *
 * Sources: src/data/video-summaries-*.js for shipped entries, plus
 * data-cache/generated/*.json for a batch that has not landed yet.
 *
 * Usage:
 *   node scripts/lint-video-summaries.mjs                 # shipped corpus
 *   node scripts/lint-video-summaries.mjs --generated     # pending batch too
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'src', 'data');
const GENERATED = path.join(ROOT, 'data-cache', 'generated');
const TRANSCRIPTS = path.join(ROOT, 'data-cache', 'transcripts');
const includeGenerated = process.argv.includes('--generated');
const onlyGenerated = process.argv.includes('--generated-only');

const errors = [];
const warnings = [];
const err = (id, msg) => errors.push(`${id}: ${msg}`);
const warn = (id, msg) => warnings.push(`${id}: ${msg}`);

function transcriptFor(videoId) {
  const p = path.join(TRANSCRIPTS, videoId + '.json');
  if (!fs.existsSync(p)) return null;
  try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return null; }
}

// The recording's real length is the playlist item's `duration` (seconds).
// Captions routinely stop well before the video ends — one 126 min lecture
// has captions to 112 min — so the last segment is a floor, never the length.
function transcriptSeconds(t) {
  if (typeof t?.duration === 'number' && t.duration > 0) return t.duration;
  const last = t?.segments?.[t.segments.length - 1];
  return last ? (last.start || 0) + (last.dur || 0) : 0;
}

// "[12:34]" and "[12:34-56:78]" and the "[1:02:03]" form some lectures use.
function timestampsIn(md) {
  const out = [];
  const re = /\[(\d{1,2}:\d{2}(?::\d{2})?)(?:\s*[-–]\s*(\d{1,2}:\d{2}(?::\d{2})?))?\]/g;
  let m;
  while ((m = re.exec(md))) {
    for (const raw of [m[1], m[2]]) {
      if (!raw) continue;
      const parts = raw.split(':').map(Number);
      out.push(parts.length === 3 ? parts[0] * 3600 + parts[1] * 60 + parts[2] : parts[0] * 60 + parts[1]);
    }
  }
  return out;
}

function checkEntry(id, e, origin) {
  if (e.videoId !== id) err(id, `videoId field is "${e.videoId}" (${origin})`);
  if (!e.subject) err(id, 'no subject');
  if (typeof e.summary !== 'string' || e.summary.trim().length < 200) {
    err(id, `summary is ${e.summary ? e.summary.length : 0} chars`);
    return;
  }
  const md = e.summary;

  // Never describe how the summary was made. Match self-reference, not the
  // words themselves: one COM III lecture is *about* AI tools and compares
  // ChatGPT in a table, which is lecture content and must not trip the gate.
  const meta = md.match(/generated by (an? )?(AI|Claude|GPT|LLM)|as an AI language model|ในฐานะ(ที่เป็น)?(AI|โมเดล)|สรุปโดย (AI|Claude|โมเดล)/i);
  if (meta) err(id, `summary refers to its own production ("${meta[0]}")`);

  // Palm's standing rule: the middle dot is not a separator in reader-facing copy.
  const dots = (md.match(/·/g) || []).length;
  if (dots) warn(id, `${dots} middle dot separator(s)`);

  if (!/^#\s+\S/m.test(md)) warn(id, 'no H1 heading');
  const sections = (md.match(/^##\s+/gm) || []).length;
  if (sections === 0) warn(id, 'no sections');

  const t = transcriptFor(id);
  if (!t) { warn(id, 'no transcript on disk, timestamps unverifiable'); return; }
  const secs = transcriptSeconds(t);
  if (!secs) { warn(id, 'transcript has no timing'); return; }

  // A timestamp past the end of the recording is the cheapest tell that a
  // section was written from expectation rather than from the recording.
  const stamps = timestampsIn(md);
  if (!stamps.length) warn(id, 'no timestamps in summary');
  const over = stamps.filter((s) => s > secs + 90);
  if (over.length) {
    const worst = Math.max(...over);
    err(id, `${over.length} timestamp(s) past the end of a ${Math.round(secs / 60)} min recording ` +
            `(worst ${Math.floor(worst / 60)}:${String(worst % 60).padStart(2, '0')})`);
  }

  if (typeof e.durationMin === 'number') {
    const real = Math.round(secs / 60);
    if (Math.abs(e.durationMin - real) > 3) err(id, `durationMin ${e.durationMin} vs transcript ${real} min`);
  }

  // An exam claim the lecturer never made would be the costliest invention
  // here — but a summary can also draw examFormat from the slides or a past
  // paper, which the captions would not show. So this reports for review
  // rather than failing: 15 shipped summaries are in exactly that position,
  // and the gate cannot tell an outside source from an invention.
  if (e.examFormat) {
    const said = t.segments.some((s) => /ข้อสอบ|สอบ|ออกสอบ|มิดเทอม|ไฟนอล|quiz|exam/i.test(s.text));
    if (!said) warn(id, 'examFormat asserted, recording never mentions an exam — check its source');
  }
}

let checked = 0;
if (!onlyGenerated) {
  const files = fs.readdirSync(DATA).filter((f) => /^video-summaries-.+\.js$/.test(f) && !f.includes('meta'));
  for (const f of files) {
    const mod = await import(pathToFileURL(path.join(DATA, f)).href);
    for (const key of Object.keys(mod)) {
      const obj = mod[key];
      if (!obj || typeof obj !== 'object') continue;
      for (const [id, e] of Object.entries(obj)) { checkEntry(id, e, f); checked++; }
    }
  }
}
if (includeGenerated || onlyGenerated) {
  if (fs.existsSync(GENERATED)) {
    for (const f of fs.readdirSync(GENERATED).filter((n) => n.endsWith('.json'))) {
      let raw;
      try { raw = JSON.parse(fs.readFileSync(path.join(GENERATED, f), 'utf8')); }
      catch (e) { err(f, 'not valid JSON: ' + e.message); continue; }
      if (raw.videoId !== f.replace('.json', '')) err(f, `videoId "${raw.videoId}" does not match filename`);
      checkEntry(raw.videoId || f, raw, 'generated');
      checked++;
    }
  }
}

console.log(`checked ${checked} summaries`);
for (const w of warnings) console.log('  warn  ' + w);
for (const e of errors) console.log('  ERROR ' + e);
console.log(`\n${errors.length} error(s), ${warnings.length} warning(s).`);
process.exit(errors.length ? 1 : 0);
