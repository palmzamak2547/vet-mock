#!/usr/bin/env node
// The environment contract (scripts/lib/env-list.mjs) against the code.
//
//   node scripts/env-contract.mjs --check   (npm run lint:env, in lint:data)
//   node scripts/env-contract.mjs --write   rewrite .env.example and docs/ENV.md
//
// --check fails when the code reads a name the list lacks, when the list holds
// a name nothing reads, or when .env.example or docs/ENV.md is not what
// --write would produce. It reads tracked source only, never an .env file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENV, PLATFORM } from './lib/env-list.mjs';
import { scanEnv } from './lib/env-scan.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXAMPLE = '.env.example';
const DOC = 'docs/ENV.md';

function runtimeOf(file) {
  if (/^supabase\/functions\//.test(file)) return 'edge function';
  if (/^api\//.test(file) || /^(vca|ai|research)\/(api|functions)\//.test(file)) return 'function';
  if (/^(src|ai\/src|vca\/src|research\/src)\//.test(file) && !/\/(landing\/og|scripts)\//.test(file)) return 'browser build';
  if (/(^|\/)(tests|playwright\.config)/.test(file)) return 'test';
  if (/^vite\.config|\/vite\.config/.test(file)) return 'build';
  return 'script';
}

// The list in its own order, each group together where it first appears.
const GROUPS = [...new Set(ENV.map((e) => e.group))];
const ORDERED = [...ENV].sort((a, b) => GROUPS.indexOf(a.group) - GROUPS.indexOf(b.group));

export function contract(root = ROOT) {
  const found = scanEnv(root);
  const listed = new Map(ENV.map((e) => [e.name, e]));
  const platform = new Map(PLATFORM);
  const problems = [];
  const dupes = ENV.map((e) => e.name).filter((n, i, all) => all.indexOf(n) !== i);
  for (const n of dupes) problems.push(`${n} is listed twice`);
  for (const [name, files] of found) {
    if (!listed.has(name) && !platform.has(name)) problems.push(`${name} is read (${files.slice(0, 2).join(', ')}) but not in scripts/lib/env-list.mjs`);
  }
  for (const name of [...listed.keys(), ...platform.keys()]) {
    if (!found.has(name)) problems.push(`${name} is in scripts/lib/env-list.mjs but nothing reads it`);
  }
  return { found, problems };
}

export function renderExample() {
  const lines = [
    '# Every environment variable VetMock reads, by name. Never put a value in',
    '# this file: values live in Vercel, Supabase secrets, GitHub Actions or a',
    '# local .env.local (gitignored). Generated from scripts/lib/env-list.mjs by',
    '# `node scripts/env-contract.mjs --write`; docs/ENV.md says where each is read.',
    '# Variables the platform sets (CI, VERCEL_ENV, ...) are listed there only.',
  ];
  let group = '';
  for (const e of ORDERED) {
    if (e.group !== group) { lines.push('', `# ── ${e.group} ──`); group = e.group; }
    lines.push(`# ${e.need}: ${e.does}`, `${e.name}=`);
  }
  return `${lines.join('\n')}\n`;
}

export function renderDoc(found) {
  const cell = (s) => String(s).replace(/\|/g, '\\|');
  const out = [
    '# Environment variables',
    '',
    'Generated by `node scripts/env-contract.mjs --write` from `scripts/lib/env-list.mjs`, the one list; do not edit by hand.',
    '`npm run lint:env` (in `lint:data`) fails when the code reads a name the list lacks, the list holds a name nothing reads, or this file or `.env.example` is stale.',
    '',
    'Where values live: the Vercel project `vetmock` (browser build and functions), Supabase edge function secrets (`supabase/functions/*`), the Vercel projects of `ai/`, `vca/` and `research/` for their own builds, GitHub Actions for CI, and a local `.env.local` for scripts. None is in this repository.',
    '',
    '- **required**: production breaks without it, as the last column says.',
    '- **optional**: a feature turns off or a default applies.',
    '- Runtime: *browser build* is baked in by Vite at build time (a change needs a rebuild); *function* is read by a Vercel function per request; *edge function* by a Supabase function; *script*, *test* and *build* run on a machine or in CI.',
    '',
    `${ENV.length} names, ${ENV.filter((e) => e.need === 'required').length} required; ${PLATFORM.length} more are set by the platform.`,
  ];
  let group = '';
  for (const e of ORDERED) {
    if (e.group !== group) {
      out.push('', `## ${e.group}`, '', '| Name | Need | Runtime | Read in | Without it / what it does |', '|---|---|---|---|---|');
      group = e.group;
    }
    const files = found.get(e.name) || [];
    const runtimes = [...new Set(files.map(runtimeOf))].join(', ');
    const where = files.slice(0, 3).map((f) => `\`${f}\``).join(', ') + (files.length > 3 ? ` +${files.length - 3}` : '');
    out.push(`| \`${e.name}\` | ${e.need} | ${runtimes} | ${where} | ${cell(e.does)} |`);
  }
  out.push('', '## Set by the platform', '', '| Name | Read in | Meaning |', '|---|---|---|');
  for (const [name, meaning] of PLATFORM) {
    const files = found.get(name) || [];
    out.push(`| \`${name}\` | ${files.slice(0, 3).map((f) => `\`${f}\``).join(', ')}${files.length > 3 ? ` +${files.length - 3}` : ''} | ${cell(meaning)} |`);
  }
  out.push('', '## How names are found', '', 'scripts/lib/env-scan.mjs reads tracked source (not unit tests, docs or static files, and never an .env file): `process.env.X`, `import.meta.env.X`, `Deno.env.get(\'X\')`, Python\'s `os.environ`, a destructure of `process.env`, and `env.X` in a file that takes `env = process.env`. A name built at run time (`process.env[name]`) is not seen: write it out.', '');
  return out.join('\n');
}

const same = (file, text) => fs.existsSync(path.join(ROOT, file)) && fs.readFileSync(path.join(ROOT, file), 'utf8').replace(/\r\n/g, '\n') === text;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { found, problems } = contract();
  const example = renderExample();
  const doc = renderDoc(found);
  if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(ROOT, EXAMPLE), example);
    fs.writeFileSync(path.join(ROOT, DOC), doc);
    console.log(`wrote ${EXAMPLE} and ${DOC}`);
  } else {
    if (!same(EXAMPLE, example)) problems.push(`${EXAMPLE} is stale: run node scripts/env-contract.mjs --write`);
    if (!same(DOC, doc)) problems.push(`${DOC} is stale: run node scripts/env-contract.mjs --write`);
  }
  for (const p of problems) console.log(`✗ ${p}`);
  console.log(`lint:env: ${found.size} names read, ${ENV.length} listed + ${PLATFORM.length} platform, ${problems.length} problem(s)`);
  process.exitCode = problems.length ? 1 : 0;
}
