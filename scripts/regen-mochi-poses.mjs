// Still poses for ordinary UI use the same source artwork as the full rig.
// Native images keep an optional illustration failure out of chunk recovery.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { STATES } from '../src/lib/motion-kit/mochi/motion.js';
import { mascotSVG } from '../src/lib/motion-kit/mochi/svg-art.js';

const directory = new URL('../public/motion/poses/', import.meta.url);
const registry = new URL('../src/data/mochi-poses.generated.js', import.meta.url);
const check = process.argv.includes('--check');
const assets = {}, expected = new Set();
let stale = false;
if (!check) fs.mkdirSync(directory, { recursive: true });
for (const [pose, meta] of Object.entries(STATES)) {
  const svg = mascotSVG(pose, meta.duration * .4, { label: `Mochi — ${meta.label}` }) + '\n';
  const hash = createHash('sha256').update(svg).digest('hex').slice(0, 10);
  const name = `${pose}.${hash}.svg`;
  expected.add(name);
  assets[pose] = `/motion/poses/${name}`;
  const target = new URL(name, directory);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== svg) stale = true;
  } else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== svg) fs.writeFileSync(target, svg);
}
const code = '// Generated by scripts/regen-mochi-poses.mjs; edit the Motion Kit source artwork.\n'
  + `export const MOCHI_POSE_ASSETS = Object.freeze(${JSON.stringify(assets, null, 2)});\n`;
if (check) {
  if (!fs.existsSync(registry) || fs.readFileSync(registry, 'utf8') !== code) stale = true;
} else if (!fs.existsSync(registry) || fs.readFileSync(registry, 'utf8') !== code) fs.writeFileSync(registry, code);
// Only remove obsolete files bearing this generator's owned hash/name format.
for (const name of fs.existsSync(directory) ? fs.readdirSync(directory) : []) {
  if (!/^[a-z]+\.[a-f0-9]{10}\.svg$/.test(name) || expected.has(name)) continue;
  if (check) stale = true;
  else fs.unlinkSync(new URL(name, directory));
}
if (stale) { console.error('Mochi poses are stale; run npm run regen:mochi'); process.exit(1); }
console.log(`${Object.keys(assets).length} Mochi poses ${check ? 'verified' : 'ready'} (${fileURLToPath(directory)})`);
